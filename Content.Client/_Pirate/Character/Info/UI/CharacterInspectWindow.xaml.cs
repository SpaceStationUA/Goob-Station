using Content.Client.UserInterface.Controls;
using Content.Shared._Pirate.Character.Info;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Pirate.Character.Info.UI;

[GenerateTypedNameReferences]
public sealed partial class CharacterInspectWindow : FancyWindow
{
    private EntityUid? _target;
    private IEntityManager? _entityManager;
    private EntityUid _viewer;
    private CharacterInspectInfoEvent? _info;

    public CharacterInspectWindow()
    {
        RobustXamlLoader.Load(this);
        InspectTabs.SetTabTitle(0, Loc.GetString("character-info-ic"));
        InspectTabs.SetTabTitle(1, Loc.GetString("character-info-ooc"));
        OnClose += ClearCharacter;
    }

    public void SetCharacter(EntityUid? target, IEntityManager entityManager, EntityUid viewer)
    {
        // Avoid showing one target's reply for another while requests are in flight.
        if (target != _target)
            _info = null;

        _target = target;
        _entityManager = entityManager;
        _viewer = viewer;
        ICInfo.SetCharacter(target, entityManager, viewer, _info);
        OOCInfo.SetCharacter(target, entityManager, viewer, _info);
    }

    public void ApplyInfo(CharacterInspectInfoEvent info)
    {
        _info = info;
        if (_entityManager != null)
            SetCharacter(_target, _entityManager, _viewer);
    }

    public void ClearCharacter()
    {
        _target = null;
        _info = null;
        ICInfo.ClearCharacter();
        OOCInfo.ClearCharacter();
    }
}
