namespace Content.Client._Pirate.Paper;

/// <summary>
/// Pirate: the cover picker, laid out like the agent ID card menu - a search box over a
/// grid of buttons, each showing the sprite of the book whose cover it would put on.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class BookSkinWindow : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;
    [Dependency] private readonly IComponentFactory _compFactory = default!;
    [Dependency] private readonly IEntitySystemManager _entitySystems = default!;

    private readonly BookSkinSystem _cover;
    private readonly TagSystem _tag;

    /// <summary>Fired with the cover the player picked.</summary>
    public event Action<EntProtoId>? OnCoverSelected;

    private readonly List<EntityPrototype> _looks = new();

    private string? _current;
    private string _filter = string.Empty;
    private EntityUid _owner;

    private const float CoverSize = 84f;

    public BookSkinWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _cover = _entitySystems.GetEntitySystem<BookSkinSystem>();
        _tag = _entitySystems.GetEntitySystem<TagSystem>();

        Search.OnTextChanged += args =>
        {
            _filter = args.Text;
            RebuildGrid();
        };
    }

    /// <summary>
    /// Fills the window with every cover the server would accept, highlighting the one
    /// the book is wearing right now.
    /// </summary>
    public void Populate(string? currentSkin, ProtoId<TagPrototype> sourceTag, EntityUid owner)
    {
        _owner = owner;
        _looks.Clear();
        _looks.AddRange(BookSkinLooks.Get(_proto, _compFactory, _tag, sourceTag).Where(HasSwappableCover));

        _current = currentSkin;
        RebuildGrid();
    }

    private void RebuildGrid()
    {
        CoverGrid.RemoveAllChildren();

        var group = new ButtonGroup();

        foreach (var look in _looks)
        {
            if (!MatchesFilter(look))
                continue;

            var preview = _cover.GetCoverPreview(_owner, new EntProtoId(look.ID));

            var button = new Button
            {
                Group = group,
                Pressed = string.Equals(look.ID, _current, StringComparison.Ordinal),
                ToolTip = look.Name,
                SetSize = new Vector2(CoverSize, CoverSize),
            };

            if (preview != null)
            {
                button.AddChild(new LayeredTintRect
                {
                    Layers = preview,
                    TextureScale = new Vector2(1.5f, 1.5f),
                    HorizontalAlignment = Control.HAlignment.Center,
                    VerticalAlignment = Control.VAlignment.Center,
                });
            }
            else
            {
                button.AddChild(new Label { Text = look.Name });
            }

            var id = new EntProtoId(look.ID);
            button.OnPressed += _ => OnCoverSelected?.Invoke(id);
            CoverGrid.AddChild(button);
        }
    }

    /// <summary>
    /// Skips books whose sprite cannot be transplanted at all: their states live in
    /// another RSI and match no swappable role (cover/decor/icon/overlay/paper), so
    /// picking one would silently change nothing.
    /// </summary>
    private bool HasSwappableCover(EntityPrototype look)
    {
        if (!look.TryGetComponent(out SpriteComponent? sprite, _compFactory))
            return false;

        foreach (var layer in sprite.AllLayers)
        {
            if (BookSkinSystem.RoleOf(layer.RsiState.Name) != null)
                return true;
        }

        return false;
    }

    private bool MatchesFilter(EntityPrototype look)
    {
        if (string.IsNullOrWhiteSpace(_filter))
            return true;

        return look.Name.Contains(_filter, StringComparison.CurrentCultureIgnoreCase);
    }

    /// <summary>
    /// Pirate: stacks the preview layers the way the in-game sprite draws them, tinting
    /// each one with its layer colour - LayeredTextureRect carries no colours, and the
    /// colours are what make the cover in the menu look like the cover in game.
    /// </summary>
    private sealed class LayeredTintRect : Control
    {
        public List<(Texture Texture, Color Color)> Layers = new();
        public Vector2 TextureScale = Vector2.One;

        protected override void Draw(DrawingHandleScreen handle)
        {
            base.Draw(handle);

            foreach (var (texture, color) in Layers)
            {
                var rect = UIBox2.FromDimensions(Vector2.Zero, texture.Size * TextureScale * UIScale);
                handle.DrawTextureRect(texture, rect, color);
            }
        }

        protected override Vector2 MeasureOverride(Vector2 availableSize)
        {
            if (Layers.Count == 0)
                return Vector2.Zero;

            var largestX = 0;
            var largestY = 0;
            foreach (var (texture, _) in Layers)
            {
                largestX = Math.Max(texture.Width, largestX);
                largestY = Math.Max(texture.Height, largestY);
            }

            return new Vector2(largestX, largestY) * TextureScale;
        }
    }
}
