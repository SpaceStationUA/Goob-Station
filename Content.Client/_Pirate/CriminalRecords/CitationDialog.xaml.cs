using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Pirate.CriminalRecords;
using Content.Shared._Pirate.StationRecords;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Pirate.CriminalRecords;

[GenerateTypedNameReferences]
public sealed partial class CitationDialog : FancyWindow
{
    private static readonly Color ErrorColor = Color.FromHex("#FF4A4A");
    private static readonly int MaxFineDigits = CriminalRecordCitations.MaxFine.ToString().Length;

    public event Action<string, string, int>? OnConfirmed;

    public CitationDialog()
    {
        RobustXamlLoader.Load(this);

        ReasonInput.PlaceHolder = Loc.GetString("criminal-records-citation-dialog-reason-placeholder");
        ReasonInput.IsValid = text => text.Length <= CriminalRecordCitations.MaxReasonLength;
        FineInput.IsValid = text => text.Length == 0
            || text.Length <= MaxFineDigits && text.All(c => c is >= '0' and <= '9') && int.Parse(text) <= CriminalRecordCitations.MaxFine;
        FineInput.PlaceHolder = Loc.GetString("criminal-records-citation-dialog-fine-placeholder", ("max", CriminalRecordCitations.MaxFine));
        DetailsInput.Placeholder = new Rope.Leaf(Loc.GetString("criminal-records-citation-dialog-details-placeholder"));

        ReasonInput.OnTextChanged += _ => UpdateState();
        FineInput.OnTextChanged += _ => UpdateState();
        DetailsInput.OnTextChanged += _ => UpdateState();
        IssueButton.OnPressed += _ => Confirm();
        CancelButton.OnPressed += _ => Close();
        UpdateState();
    }

    protected override void Opened()
    {
        base.Opened();
        ReasonInput.GrabKeyboardFocus();
    }

    private string Reason => RecordLogNotes.Sanitize(ReasonInput.Text);

    private string Details => RecordLogNotes.Sanitize(Rope.Collapse(DetailsInput.TextRope));

    private int? Fine => int.TryParse(FineInput.Text, out var fine) && fine is > 0 and <= CriminalRecordCitations.MaxFine
        ? fine
        : null;

    private void UpdateState()
    {
        var length = Details.Length;
        var tooLong = length > CriminalRecordCitations.MaxDetailsLength;
        Counter.Text = $"{length}/{CriminalRecordCitations.MaxDetailsLength}";
        Counter.FontColorOverride = tooLong ? ErrorColor : Color.DarkGray;
        IssueButton.Disabled = Reason.Length == 0 || Fine == null || tooLong;
    }

    private void Confirm()
    {
        if (Fine is not { } fine || Reason.Length == 0 || Details.Length > CriminalRecordCitations.MaxDetailsLength)
            return;

        OnConfirmed?.Invoke(Reason, Details, fine);
        Close();
    }
}
