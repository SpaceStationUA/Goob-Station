using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Pirate.CriminalRecords;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Pirate.CriminalRecords;

[GenerateTypedNameReferences]
public sealed partial class CitationPaymentConsoleWindow : FancyWindow
{
    public event Action<uint, uint>? OnPay;
    private CitationPaymentConsoleState _state = new(new(), false);
    private uint? _selectedId;
    private bool _updatingList;

    public CitationPaymentConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        PeopleList.OnItemSelected += args =>
        {
            if (_updatingList || PeopleList[args.ItemIndex].Metadata is not uint id || _selectedId == id)
                return;

            Citations.CloseDialog();
            _selectedId = id;
            SyncHighlight();
            UpdateSelection();
        };
        PeopleList.OnItemDeselected += _ => SyncHighlight();
        Citations.OnPay += id =>
        {
            if (_selectedId is { } recordId)
                OnPay?.Invoke(recordId, id);
        };
        UpdateState(_state);
    }

    public void UpdateState(CitationPaymentConsoleState state)
    {
        _state = state;
        if (!_state.People.Any(p => p.RecordId == _selectedId))
            _selectedId = null;

        RebuildPeople();
        UpdateSelection();
    }

    private void RebuildPeople()
    {
        var entries = new List<ItemList.Item>();
        foreach (var person in _state.People)
        {
            entries.Add(new ItemList.Item(PeopleList)
            {
                Text = person.Name,
                Metadata = person.RecordId,
                TooltipText = Loc.GetString("citation-payment-person-total", ("job", person.Job),
                    ("fine", person.Citations.Sum(c => (long) c.Fine))),
            });
        }

        entries.Sort(ComparePeople);
        _updatingList = true;
        try
        {
            PeopleList.SetItems(entries, ComparePeople);
        }
        finally
        {
            _updatingList = false;
        }
        SyncHighlight();
        NoPeople.Visible = PeopleList.Count == 0;
        NoPeople.Text = Loc.GetString("citation-payment-empty");
    }

    private void SyncHighlight()
    {
        if (_updatingList)
            return;

        _updatingList = true;
        try
        {
            foreach (var item in PeopleList)
                item.Selected = item.Metadata is uint id && id == _selectedId;
        }
        finally
        {
            _updatingList = false;
        }
    }

    private static int ComparePeople(ItemList.Item a, ItemList.Item b)
    {
        var result = string.Compare(a.Text, b.Text, StringComparison.CurrentCultureIgnoreCase);
        return result != 0 ? result : ((uint?) a.Metadata ?? 0).CompareTo((uint?) b.Metadata ?? 0);
    }

    private void UpdateSelection()
    {
        var person = _state.People.Find(p => p.RecordId == _selectedId);
        Citations.Visible = person != null;
        JobLabel.Visible = person != null;
        EmptyLabel.Visible = person == null;
        EmptyLabel.Text = Loc.GetString(!_state.HasStation ? "citation-payment-no-station"
            : _state.People.Count == 0 ? "citation-payment-empty" : "citation-payment-select-person");

        if (person == null)
        {
            Citations.CloseDialog();
            return;
        }

        JobLabel.Text = person.Job;
        Citations.UpdateCitations(person.RecordId, person.Name, person.Citations, canEdit: false);
    }
}
