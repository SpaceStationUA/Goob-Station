using System.Linq;
using System.Numerics;
using Content.Client._Pirate.StationRecords;
using Content.Shared._Pirate.CriminalRecords;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Pirate.CriminalRecords;

[GenerateTypedNameReferences]
public sealed partial class RecordCitationsPanel : BoxContainer
{
    public event Action<string, string, int>? OnAddCitation;
    public event Action<uint>? OnPay;
    public event Action<uint>? OnVoid;

    private readonly SpriteSystem _sprite;
    private CitationDialog? _dialog;
    private uint? _recordKey;
    private List<CriminalRecordCitation> _citations = new();
    private bool _canEdit;

    private (uint Id, bool Void)? _confirm;

    public RecordCitationsPanel()
    {
        RobustXamlLoader.Load(this);
        _sprite = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>();
        IssueButton.OnPressed += _ => OpenIssueDialog();
    }

    public static int ActiveCount(IEnumerable<CriminalRecordCitation> citations)
    {
        return citations.Count(c => c.Status == CitationStatus.Active);
    }

    public void UpdateCitations(uint recordKey, string name, IReadOnlyList<CriminalRecordCitation> citations, bool canEdit)
    {
        if (_recordKey != recordKey)
        {
            _recordKey = recordKey;
            _confirm = null;
            _dialog?.Close();
        }

        PersonName.Text = name;
        IssueButton.Visible = canEdit;
        _canEdit = canEdit;

        _citations = citations
            .OrderBy(c => c.Status != CitationStatus.Active)
            .ThenByDescending(c => c.Id)
            .ToList();

        var outstanding = _citations.Where(c => c.Status == CitationStatus.Active).Sum(c => c.Fine);
        Outstanding.Text = Loc.GetString("criminal-records-citation-outstanding", ("fine", outstanding));
        Outstanding.FontColorOverride = outstanding > 0 ? StatusColor(CitationStatus.Active) : Color.DarkGray;

        if (_confirm is { } confirm && !_citations.Any(c => c.Id == confirm.Id && c.Status == CitationStatus.Active))
            _confirm = null;

        Rebuild();
    }

    public void CloseDialog()
    {
        _dialog?.Close();
        _confirm = null;
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
            _dialog?.Close();

        base.Dispose(disposing);
    }

    private void Rebuild()
    {
        Entries.RemoveAllChildren();
        foreach (var citation in _citations)
        {
            Entries.AddChild(MakeEntry(citation));
        }

        NoEntries.Visible = _citations.Count == 0;
    }

    private Control MakeEntry(CriminalRecordCitation citation)
    {
        var color = StatusColor(citation.Status);

        var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };
        header.AddChild(new TextureRect
        {
            Texture = _sprite.Frame0(RecordHistoryPanel.CitationIcon(citation.Status.ToString())),
            TextureScale = new Vector2(2f, 2f),
            VerticalAlignment = VAlignment.Center,
        });
        header.AddChild(new Label { Text = citation.Reason, FontColorOverride = color, ClipText = true, HorizontalExpand = true });
        header.AddChild(new Label { Text = Loc.GetString("criminal-records-citation-amount", ("fine", citation.Fine)) });
        header.AddChild(new Label
        {
            Text = Loc.GetString($"criminal-records-citation-status-{citation.Status.ToString().ToLowerInvariant()}"),
            FontColorOverride = color,
        });

        var body = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 2,
            Margin = new Thickness(8, 6),
        };
        body.AddChild(header);
        body.AddChild(Text(Loc.GetString("criminal-records-citation-issued-by",
            ("officer", citation.IssuedBy ?? Loc.GetString("criminal-records-console-unknown-officer")),
            ("time", RecordHistoryPanel.FormatTime(citation.IssuedAt))), Color.DarkGray));

        if (citation.Details.Length > 0)
            body.AddChild(Text(citation.Details, null));

        if (citation.Status != CitationStatus.Active)
        {
            body.AddChild(Text(Loc.GetString($"criminal-records-citation-closed-{citation.Status.ToString().ToLowerInvariant()}",
                ("name", citation.ClosedBy ?? Loc.GetString("criminal-records-console-unknown-officer")),
                ("time", citation.ClosedAt is { } closed ? RecordHistoryPanel.FormatTime(closed) : string.Empty)), Color.DarkGray));
        }
        else
        {
            body.AddChild(MakeActions(citation));
        }

        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#1B1B21"),
                BorderColor = color.WithAlpha(0.6f),
                BorderThickness = new Thickness(3, 0, 0, 0),
            },
        };
        panel.AddChild(body);
        return panel;
    }

    private Control MakeActions(CriminalRecordCitation citation)
    {
        var actions = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalAlignment = HAlignment.Right,
            SeparationOverride = 4,
            Margin = new Thickness(0, 4, 0, 0),
        };

        var id = citation.Id;
        var confirmingPay = _confirm == (id, false);
        var pay = new Button
        {
            Text = confirmingPay
                ? Loc.GetString("criminal-records-citation-pay-confirm", ("fine", citation.Fine))
                : Loc.GetString("criminal-records-citation-pay"),
            StyleClasses = { "ButtonColorGreen" },
        };
        pay.OnPressed += _ => Press(id, false, () => OnPay?.Invoke(id));
        actions.AddChild(pay);

        if (!_canEdit)
            return actions;

        var confirmingVoid = _confirm == (id, true);
        var @void = new Button
        {
            Text = Loc.GetString(confirmingVoid ? "criminal-records-citation-void-confirm" : "criminal-records-citation-void"),
            StyleClasses = { "ButtonColorRed" },
        };
        @void.OnPressed += _ => Press(id, true, () => OnVoid?.Invoke(id));
        actions.AddChild(@void);
        return actions;
    }

    private void Press(uint id, bool isVoid, Action send)
    {
        if (_confirm == (id, isVoid))
        {
            _confirm = null;
            send();
        }
        else
        {
            _confirm = (id, isVoid);
        }

        Rebuild();
    }

    private static Color StatusColor(CitationStatus status)
    {
        return status switch
        {
            CitationStatus.Active => Color.FromHex("#E0A030"),
            CitationStatus.Paid => Color.FromHex("#8FC72A"),
            _ => Color.FromHex("#8A8A8A"),
        };
    }

    private static RichTextLabel Text(string text, Color? color)
    {
        var message = new FormattedMessage();
        if (color is { } c)
            message.PushColor(c);
        message.AddText(text);
        if (color != null)
            message.Pop();

        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMessage(message);
        return label;
    }

    private void OpenIssueDialog()
    {
        if (_dialog != null)
        {
            _dialog.MoveToFront();
            return;
        }

        _dialog = new CitationDialog();
        _dialog.OnConfirmed += (reason, details, fine) => OnAddCitation?.Invoke(reason, details, fine);
        _dialog.OnClose += () => { _dialog = null; };
        _dialog.OpenCentered();
        RecordConsoleSounds.AttachDialog(this, _dialog);
    }
}
