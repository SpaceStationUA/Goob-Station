using Content.Client._Pirate.Lobby.UI.Background;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Pirate.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class OOCInfoEditor : Control
{
    private readonly BackgroundSection _section;
    private readonly BackgroundTextField _personalNotes;
    private readonly BackgroundTextField _oocNotes;

    public Control PersonalNotes => _personalNotes;
    public Control OOCNotes => _oocNotes;

    public TextEdit PersonalNotesInput => _personalNotes.Input;
    public TextEdit OOCNotesInput => _oocNotes.Input;

    public OOCInfoEditor()
    {
        RobustXamlLoader.Load(this);

        _section = new BackgroundSection(Loc.GetString("humanoid-profile-editor-ooc-info-heading"), BackgroundStyle.Ooc);
        _personalNotes = Field("background-tab-personal-notes", "character-info-editor-personal-notes-placeholder");
        _oocNotes = Field("background-tab-ooc-notes", "character-info-editor-ooc-notes-placeholder");
        Root.AddChild(_section);
        _section.SetProgress(0, 0);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var total = (_personalNotes.Visible ? 1 : 0) + (_oocNotes.Visible ? 1 : 0);
        var filled = (_personalNotes.Visible && _personalNotes.IsFilled ? 1 : 0)
            + (_oocNotes.Visible && _oocNotes.IsFilled ? 1 : 0);

        if (filled != _section.Filled || total != _section.Total)
            _section.SetProgress(filled, total);
    }

    private BackgroundTextField Field(string name, string hint)
    {
        var field = new BackgroundTextField(Loc.GetString(name), Loc.GetString(hint), BackgroundStyle.Ooc,
            HumanoidCharacterProfile.MaxCharacterInfoLength);
        _section.Body.AddChild(field);
        return field;
    }
}
