using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Pirate.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class RecordBackgroundEditor : Control
{
    public RecordBackgroundEditor()
    {
        RobustXamlLoader.Load(this);

        Setup(SecurityInput, SecurityCounter, "record-background-editor-security-placeholder");
        Setup(CrewInput, CrewCounter, "record-background-editor-crew-placeholder");
        Setup(PsionicsInput, PsionicsCounter, "record-background-editor-psionics-placeholder");
    }

    // Code-set text does not raise OnTextChanged.
    public void UpdateCounters()
    {
        UpdateCounter(SecurityInput, SecurityCounter);
        UpdateCounter(CrewInput, CrewCounter);
        UpdateCounter(PsionicsInput, PsionicsCounter);
    }

    private static void Setup(TextEdit input, Label counter, string placeholder)
    {
        input.Placeholder = new Rope.Leaf(Loc.GetString(placeholder));
        input.OnTextChanged += _ => UpdateCounter(input, counter);
        UpdateCounter(input, counter);
    }

    private static void UpdateCounter(TextEdit input, Label counter)
    {
        var length = input.TextLength;
        counter.Text = $"{length}/{HumanoidCharacterProfile.MaxRecordBackgroundLength}";
        counter.FontColorOverride = length > HumanoidCharacterProfile.MaxRecordBackgroundLength
            ? Color.FromHex("#FF4A4A")
            : Color.DarkGray;
    }
}
