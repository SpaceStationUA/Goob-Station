using System.Numerics;
using Content.Client._Pirate.Lobby.UI.Background;
using Content.Shared._Pirate.StationRecords;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Pirate.Lobby.UI;
[GenerateTypedNameReferences]
public sealed partial class RecordBackgroundEditor : Control
{
    private const float LabelWidth = 90;
    public event Action? OnChanged;

    private readonly Dictionary<RecordLogBook, Section> _sections = new();
    private readonly BackgroundSection _section;
    private static readonly (RecordLogBook Book, string Name)[] Books =
    [
        (RecordLogBook.Security, "security"),
        (RecordLogBook.Crew, "crew"),
        (RecordLogBook.Psionics, "psionics"),
    ];

    public RecordBackgroundEditor()
    {
        RobustXamlLoader.Load(this);

        _section = new BackgroundSection(Loc.GetString("humanoid-profile-editor-records-heading"), BackgroundStyle.Records);
        Sections.AddChild(_section);

        var hint = new RichTextLabel { StyleClasses = { "TraitsEntryDescriptionLabel" }, HorizontalExpand = true };
        hint.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("background-tab-records-hint")));
        _section.Body.AddChild(hint);

        foreach (var (book, name) in Books)
        {
            var section = new Section(this, book, name);
            _sections[book] = section;
            _section.Body.AddChild(section.Root);
        }

        UpdateStats();
    }

    private void UpdateStats()
    {
        var count = 0;
        foreach (var section in _sections.Values)
        {
            count += section.Count;
        }

        _section.SetStats(Loc.GetString("background-tab-records-count", ("count", count)));
    }
    public void SetEntries(IEnumerable<RecordBackgroundEntry> entries)
    {
        foreach (var section in _sections.Values)
        {
            section.Clear();
        }

        foreach (var entry in entries)
        {
            if (_sections.TryGetValue(entry.Book, out var section))
                section.Add(entry);
        }

        foreach (var section in _sections.Values)
        {
            section.UpdateHeader();
        }

        UpdateStats();
    }
    public List<RecordBackgroundEntry> GetEntries()
    {
        var result = new List<RecordBackgroundEntry>();
        foreach (var (book, _) in Books)
        {
            result.AddRange(_sections[book].GetEntries());
        }

        return result;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        foreach (var section in _sections.Values)
        {
            section.FitScrollBars();
        }
    }

    private void RaiseChanged()
    {
        UpdateStats();
        OnChanged?.Invoke();
    }
    private sealed class Section
    {
        public readonly BoxContainer Root;
        private readonly RecordBackgroundEditor _editor;
        private readonly RecordLogBook _book;
        private readonly string _name;
        private readonly BoxContainer _entries;
        private readonly Label _count;
        private readonly FlatButton _add;
        private readonly Label _empty;
        private readonly List<EntryControl> _controls = new();

        public Section(RecordBackgroundEditor editor, RecordLogBook book, string name)
        {
            _editor = editor;
            _book = book;
            _name = name;

            Root = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 6 };

            var header = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
                Margin = new Thickness(0, 4, 0, 0),
            };
            header.AddChild(new Label
            {
                Text = Loc.GetString($"record-background-editor-{name}-label"),
                StyleClasses = { "TraitsEntryNameLabel" },
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            });
            _count = new Label
            {
                StyleClasses = { "TraitsStatLabel" },
                VerticalAlignment = VAlignment.Center,
            };
            header.AddChild(_count);
            _add = new FlatButton { Text = Loc.GetString("record-background-editor-add"), Kind = FlatButtonKind.Primary };
            _add.OnPressed += _ =>
            {
                Add(new RecordBackgroundEntry
                {
                    Book = _book,
                    Title = Loc.GetString("records-log-kind-background"),
                    Author = Loc.GetString("records-log-hr-author"),
                }, focus: true);
                UpdateHeader();
                _editor.RaiseChanged();
            };
            header.AddChild(_add);
            Root.AddChild(header);
            Root.AddChild(new PanelContainer { SetHeight = 1, PanelOverride = new StyleBoxFlat(BackgroundStyle.Line) });

            _empty = new Label
            {
                Text = Loc.GetString("record-background-editor-empty"),
                FontColorOverride = BackgroundStyle.TextFaint,
                Margin = new Thickness(4, 0, 0, 0),
            };
            Root.AddChild(_empty);

            _entries = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 6 };
            Root.AddChild(_entries);
            UpdateHeader();
        }

        public void Clear()
        {
            _controls.Clear();
            _entries.RemoveAllChildren();
        }

        public void Add(RecordBackgroundEntry entry, bool focus = false)
        {
            var control = new EntryControl(_name, entry);
            control.OnChanged += _editor.RaiseChanged;
            control.OnRemove += () =>
            {
                _controls.Remove(control);
                _entries.RemoveChild(control.Root);
                UpdateHeader();
                _editor.RaiseChanged();
            };

            _controls.Add(control);
            _entries.AddChild(control.Root);
            if (focus)
                control.FocusBody();
        }

        public IEnumerable<RecordBackgroundEntry> GetEntries()
        {
            foreach (var control in _controls)
            {
                yield return control.GetEntry(_book);
            }
        }

        public int Count => _controls.Count;

        public void FitScrollBars()
        {
            foreach (var control in _controls)
            {
                control.FitScrollBar();
            }
        }

        public void UpdateHeader()
        {
            _count.Text = $"{_controls.Count}/{RecordBackgroundEntry.MaxPerBook}";
            _add.Disabled = _controls.Count >= RecordBackgroundEntry.MaxPerBook;
            _empty.Visible = _controls.Count == 0;
        }
    }
    private sealed class EntryControl
    {
        public readonly PanelContainer Root;
        public event Action? OnChanged;
        public event Action? OnRemove;

        private readonly LineEdit _title;
        private readonly LineEdit _author;
        private readonly TextEdit _body;
        private readonly Label _counter;

        public EntryControl(string bookName, RecordBackgroundEntry entry)
        {
            _title = new LineEdit
            {
                StyleBoxOverride = BackgroundStyle.InputFrame(),
                Text = entry.Title,
                HorizontalExpand = true,
                PlaceHolder = Loc.GetString("records-log-kind-background"),
                IsValid = text => text.Length <= RecordBackgroundEntry.MaxTitleLength,
            };
            _author = new LineEdit
            {
                StyleBoxOverride = BackgroundStyle.InputFrame(),
                Text = entry.Author,
                HorizontalExpand = true,
                PlaceHolder = Loc.GetString("records-log-hr-author"),
                IsValid = text => text.Length <= RecordBackgroundEntry.MaxAuthorLength,
            };
            _body = new TextEdit
            {
                HorizontalExpand = true,
                MinSize = new Vector2(220, 100),
                Placeholder = new Rope.Leaf(Loc.GetString($"record-background-editor-{bookName}-placeholder")),
                TextRope = new Rope.Leaf(entry.Body),
            };
            _counter = new Label { StyleClasses = { "TraitsCategoryStatsLabel" }, HorizontalAlignment = HAlignment.Right };

            _title.OnTextChanged += _ => OnChanged?.Invoke();
            _author.OnTextChanged += _ => OnChanged?.Invoke();
            _body.OnTextChanged += _ =>
            {
                UpdateCounter();
                OnChanged?.Invoke();
            };

            var remove = new FlatButton
            {
                Text = Loc.GetString("record-background-editor-remove"),
                Kind = FlatButtonKind.Danger,
            };
            remove.OnPressed += _ => OnRemove?.Invoke();

            var titleRow = Row("record-background-editor-title", _title);
            titleRow.AddChild(remove);

            var content = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 4,
                Margin = new Thickness(10, 8),
            };
            content.AddChild(titleRow);
            content.AddChild(Row("record-background-editor-author", _author));
            var frame = new PanelContainer { PanelOverride = BackgroundStyle.InputFrame(), Margin = new Thickness(0, 2, 0, 0) };
            frame.AddChild(_body);
            content.AddChild(frame);
            content.AddChild(_counter);

            Root = new PanelContainer
            {
                HorizontalExpand = true,
                PanelOverride = BackgroundStyle.Card(BackgroundStyle.Records),
            };
            Root.AddChild(content);
            UpdateCounter();
        }

        public void FocusBody()
        {
            _body.GrabKeyboardFocus();
        }

        public void FitScrollBar()
        {
            BackgroundStyle.FitScrollBar(_body);
        }

        public RecordBackgroundEntry GetEntry(RecordLogBook book)
        {
            return new RecordBackgroundEntry
            {
                Book = book,
                Title = _title.Text,
                Author = _author.Text,
                Body = Rope.Collapse(_body.TextRope),
            };
        }

        private void UpdateCounter()
        {
            var length = _body.TextLength;
            _counter.Text = $"{length}/{RecordBackgroundEntry.MaxBodyLength}";
            _counter.FontColorOverride = length > RecordBackgroundEntry.MaxBodyLength ? BackgroundStyle.Bad : null;
        }

        private static BoxContainer Row(string label, Control value)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
            row.AddChild(new Label
            {
                Text = Loc.GetString(label),
                FontColorOverride = BackgroundStyle.TextDim,
                MinWidth = LabelWidth,
                VerticalAlignment = VAlignment.Center,
            });
            row.AddChild(value);
            return row;
        }
    }
}
