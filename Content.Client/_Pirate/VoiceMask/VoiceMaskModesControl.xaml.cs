using Content.Shared._Pirate.VoiceMask;
using Content.Shared.Radio;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Pirate.VoiceMask;

[GenerateTypedNameReferences]
public sealed partial class VoiceMaskModesControl : BoxContainer
{
    [Dependency] private IPrototypeManager _proto = default!;

    public event Action<SpeakerNameContext, ProtoId<RadioChannelPrototype>?, bool>? OnModeChanged;

    public VoiceMaskModesControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SayCheck.OnToggled += args => OnModeChanged?.Invoke(SpeakerNameContext.Say, null, args.Pressed);
        WhisperCheck.OnToggled += args => OnModeChanged?.Invoke(SpeakerNameContext.Whisper, null, args.Pressed);

        Visible = false;
    }

    public void UpdateState(VoiceMaskModesState? state)
    {
        Visible = state != null;
        if (state == null)
            return;

        SayCheck.Pressed = state.Say;
        WhisperCheck.Pressed = state.Whisper;

        ChannelGrid.RemoveAllChildren();
        foreach (var (channel, enabled) in state.Channels)
        {
            if (!_proto.TryIndex(channel, out var proto))
                continue;

            var check = new CheckBox
            {
                Text = proto.LocalizedName,
                Pressed = enabled,
            };
            check.Label.FontColorOverride = proto.Color;
            check.OnToggled += args => OnModeChanged?.Invoke(SpeakerNameContext.Radio, channel, args.Pressed);

            ChannelGrid.AddChild(check);
        }
    }
}
