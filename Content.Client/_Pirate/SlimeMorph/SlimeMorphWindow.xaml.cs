    public SlimeMorphWindow()
    {
        RobustXamlLoader.Load(this);

        _entManager = IoCManager.Resolve<IEntityManager>();
        _markingManager = IoCManager.Resolve<MarkingManager>();
        _humanoidSystem = _entManager.System<HumanoidAppearanceSystem>();

        foreach (var category in SlimeMorphCategories.Editable)
        {
            var picker = new SingleMarkingPicker { Category = category };
            picker.OnMarkingSelect += args =>
            {
                OnMarkingSelected?.Invoke((category, args.slot, args.id));
                PreviewMarkingSelect(category, args.slot, args.id);
            };
            picker.OnColorChanged += args =>
            {
                OnMarkingColorChanged?.Invoke((category, args.slot, args.marking));
                PreviewMarkingColor(category, args.slot, args.marking);
            };
            picker.OnSlotAdd += () => OnMarkingSlotAdded?.Invoke(category);
            picker.OnSlotRemove += slot => OnMarkingSlotRemoved?.Invoke((category, slot));

            if (FindColorContainer(picker) is { } colorBox)
            {
                colorBox.Orientation = BoxContainer.LayoutOrientation.Vertical;
                colorBox.SeparationOverride = 4;
            }

            // The picker draws its own category label; hide it and use a collapsible header instead
            // (icon + name row, styled like the traits kit's category headers).
            if (FindControlByName(picker, "CategoryName") is { } label)
                label.Visible = false;

            var expandIcon = new Label { Text = "▶", Margin = new Thickness(0, 0, 8, 0) };
            var nameLabel = new Label { Text = Loc.GetString($"markings-category-{category}") };
            // A small dot on the right of the header marks categories that currently have a marking.
            var dot = new PanelContainer
            {
                MinSize = new Vector2(8, 8),
                VerticalAlignment = VAlignment.Center,
                Visible = false,
                PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#6F9FE0") },
            };
            var headerContent = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(8, 5),
                HorizontalExpand = true,
            };
            headerContent.AddChild(expandIcon);
            headerContent.AddChild(nameLabel);
            headerContent.AddChild(new Control { HorizontalExpand = true });
            headerContent.AddChild(dot);

            var header = new ContainerButton { HorizontalExpand = true };
            header.AddChild(headerContent);

            var section = new MarkingSection { Picker = picker, Header = header, ExpandIcon = expandIcon, Dot = dot };
            header.OnPressed += _ =>
            {
                section.Collapsed = !section.Collapsed;
                ApplyCollapse(section);
            };

            var root = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(0, 0, 0, 4) };
            root.AddChild(header);
            root.AddChild(picker);
            section.Root = root;

            MarkingPickers.AddChild(root);
            _sections.Add(section);
        }

        SkinColorSelector.OnColorChanged += color =>
        {
            if (_updating)
                return;
            OnSkinColorChanged?.Invoke(color);
            PreviewField(s => s.SkinColor = color);
        };
        EyeColorSelector.OnColorChanged += color =>
        {
            if (_updating)
                return;
            OnEyeColorChanged?.Invoke(color);
            PreviewField(s => s.EyeColor = color);
        };

        InstallStyles();
        SexButton.OptionStyleClasses.Add(OptionItemClass);
        GenderButton.OptionStyleClasses.Add(OptionItemClass);
        XenotypeButton.OptionStyleClasses.Add(OptionItemClass); // Pirate: slime morph
        XenotypeButton.OnItemSelected += args =>
        {
            XenotypeButton.SelectId(args.Id);
            if (_updating)
                return;
            OnXenotypeChanged?.Invoke(args.Id >= 0 && args.Id < _xenotypeIds.Count ? _xenotypeIds[args.Id] : null);
        };

        foreach (var sex in Enum.GetValues<Sex>())
            SexButton.AddItem(Loc.GetString($"humanoid-profile-editor-sex-{sex.ToString().ToLower()}-text"), (int) sex);
        SexButton.OnItemSelected += args =>
        {
            SexButton.SelectId(args.Id);
            if (_updating)
                return;
            OnSexChanged?.Invoke((Sex) args.Id);
            PreviewField(s => s.Sex = (Sex) args.Id);
        };

        foreach (var gender in Enum.GetValues<Gender>())
            GenderButton.AddItem(Loc.GetString($"slime-morph-gender-{gender.ToString().ToLower()}"), (int) gender);
        GenderButton.OnItemSelected += args =>
        {
            GenderButton.SelectId(args.Id);
            if (_updating)
                return;
            OnGenderChanged?.Invoke((Gender) args.Id);
            PreviewField(s => s.Gender = (Gender) args.Id);
        };

        HeightSlider.OnValueChanged += _ =>
        {
            HeightValue.Text = HeightSlider.Value.ToString("0.00");
            if (_updating)
                return;
            OnHeightChanged?.Invoke(HeightSlider.Value);
            PreviewField(s => s.Height = HeightSlider.Value);
        };
        WidthSlider.OnValueChanged += _ =>
        {
            WidthValue.Text = WidthSlider.Value.ToString("0.00");
            if (_updating)
                return;
            OnWidthChanged?.Invoke(WidthSlider.Value);
            PreviewField(s => s.Width = WidthSlider.Value);
        };

        RememberedList.OnItemSelected += _ => OnListSelectionChanged();
        RememberedList.OnItemDeselected += _ => OnListSelectionChanged();

        // Pirate: slime morph - one commit button. It mimics a loaded target, otherwise applies the
