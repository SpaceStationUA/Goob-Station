    /// <summary>Show/hide a section's picker per its collapse state and refresh the header caret.</summary>
    private static void ApplyCollapse(MarkingSection section)
    {
        section.Picker.Visible = !section.Collapsed;
        section.ExpandIcon.Text = section.Collapsed ? "▶" : "▼";
    }

    private static Control? FindControlByName(Control control, string name)
    {
        foreach (var child in control.Children)
        {
            if (child.Name == name)
                return child;

            if (FindControlByName(child, name) is { } found)
                return found;
        }

        return null;
    }

    private static BoxContainer? FindColorContainer(Control control)
    {
        foreach (var child in control.Children)
        {
            if (child is BoxContainer { Name: "ColorSelectorContainer" } box)
                return box;

            if (FindColorContainer(child) is { } found)
                return found;
        }

        return null;
    }

    private void OnListSelectionChanged()
    {
        if (_updating)
            return;

        // Pirate: slime morph - the list mixes studied targets and saved looks.
        switch (RememberedList.GetSelected().FirstOrDefault()?.Metadata)
        {
            case StudiedKey studied:
                _selected = studied.Target;
                _selectedSaved = null;
                _selectedName = _state?.Remembered.FirstOrDefault(a => a.Target == studied.Target)?.Name;
                ForgetButton.Disabled = false;
                OnSelectTarget?.Invoke(studied.Target);
                break;
            case SavedKey saved:
                _selected = null;
                _selectedSaved = (saved.Name, saved.Species);
                _selectedName = saved.Name;
                ForgetButton.Disabled = false;
                OnSelectSaved?.Invoke((saved.Name, saved.Species));
                break;
            default:
                _selected = null;
                _selectedSaved = null;
                _selectedName = null;
                ForgetButton.Disabled = true;
                OnSelectTarget?.Invoke(null);
                break;
        }
    }

    public void UpdateState(SlimeMorphUiState state)
    {
        _state = state;
        _updating = true;

        SexButton.SelectId((int) state.Sex);
        GenderButton.SelectId((int) state.Gender);
        UpdateXenotypeButton(state); // Pirate: slime morph
        SkinColorSelector.Color = state.SkinColor;
        EyeColorSelector.Color = state.EyeColor;

        HeightSlider.MinValue = state.MinHeight;
        HeightSlider.MaxValue = state.MaxHeight;
        HeightSlider.Value = state.Height;
        HeightValue.Text = state.Height.ToString("0.00");

        WidthSlider.MinValue = state.MinWidth;
        WidthSlider.MaxValue = state.MaxWidth;
        WidthSlider.Value = state.Width;
        WidthValue.Text = state.Width.ToString("0.00");

        // Use the target species while mimicking.
        var pickerSpecies = state.PickerSpecies ?? state.Species;
        foreach (var section in _sections)
        {
            var picker = section.Picker;
            var category = picker.Category;
            var markings = state.MarkingSet.TryGetCategory(category, out var list)
                ? new List<Marking>(list)
                : new List<Marking>();
            var total = state.MarkingSet.PointsLeft(category) + markings.Count;
            // Used to resolve gradient icons.
            picker.GradientContext = state.MarkingSet;
            // Always scoped to the selected xenotype (defaults to the slime's own species).
            picker.IgnoreSpecies = false;
            picker.Sex = state.Sex;
            picker.UpdateData(markings, pickerSpecies, total);

            // UpdateData hides the picker when a category has no markings; fold that into the whole
            // section so empty groups vanish, and otherwise honor the collapse state.
            section.Root.Visible = picker.Visible;
            if (picker.Visible)
                ApplyCollapse(section);

            // Dot on the header marks categories that currently have a marking selected.
            section.Dot.Visible = markings.Count > 0;
        }

        UpdateRemembered(state);

        // Single commit button: enabled whenever there is a staged look to commit (always, while open).
        MimicButton.Disabled = !(state.CanApply || state.CanMimic);

        UpdatePreview(state);
        RestyleButtons();

        _updating = false;
    }

    private void UpdateRemembered(SlimeMorphUiState state)
    {
        // Preserve the saved-look selection across the rebuild: the server tracks the studied target
        // (SelectedTarget) but has no notion of a "selected saved look", so re-select it ourselves,
        // otherwise clicking a saved entry deselects on the very next state push (Forget stays greyed).
        var keepSaved = _selectedSaved;

        RememberedList.Clear();

        foreach (var appearance in state.Remembered)
        {
            var item = RememberedList.AddItem(Loc.GetString("slime-morph-remembered-entry",
                ("name", appearance.Name),
                ("species", _humanoidSystem.GetSpeciesRepresentation(appearance.Species))));
            item.Metadata = new StudiedKey(appearance.Target);
            if (state.SelectedTarget == appearance.Target)
                item.Selected = true;
        }

        // Pirate: slime morph - saved looks share the list, tagged with a star.
        foreach (var appearance in state.Saved)
        {
            var item = RememberedList.AddItem(Loc.GetString("slime-morph-saved-entry",
                ("name", appearance.Name),
                ("species", _humanoidSystem.GetSpeciesRepresentation(appearance.Species))));
            item.Metadata = new SavedKey(appearance.Name, appearance.Species);
            if (keepSaved is { } k && k.name == appearance.Name && k.species == appearance.Species)
                item.Selected = true;
        }

        if (state.SelectedTarget is { } target)
        {
            _selected = target;
            _selectedSaved = null;
        }
        else if (keepSaved is { } k2 && state.Saved.Any(a => a.Name == k2.name && a.Species == k2.species))
        {
            _selected = null;
            _selectedSaved = k2;
        }
        else
        {
            _selected = null;
            _selectedSaved = null;
        }

        ForgetButton.Disabled = _selected == null && _selectedSaved == null;
    }

    /// <summary>Populate the xenotype dropdown from the morph whitelist (defaults to the slime's own species).</summary>
    private void UpdateXenotypeButton(SlimeMorphUiState state)
    {
        XenotypeButton.Clear();
        _xenotypeIds.Clear();

        var effective = state.PickerSpecies ?? state.Species;
        var selectedId = 0;
        var id = 0;
        foreach (var species in state.MorphableSpecies)
        {
            XenotypeButton.AddItem(_humanoidSystem.GetSpeciesRepresentation(species), id);
            _xenotypeIds.Add(species);
            if (species == effective)
                selectedId = id;
            id++;
        }

        XenotypeButton.SelectId(selectedId);
    }

    /// <summary>Remember a name (e.g. an imported file's) to prefill the next Save prompt.</summary>
    public void SetSuggestedName(string? name)
    {
        _selectedName = name;
    }

    /// <summary>Prompt for a name (prefilled from the loaded memory), then store the staged look.</summary>
    private void PromptSaveName()
    {
        var dialog = new DialogWindow(
            Loc.GetString("slime-morph-save-title"),
            new List<QuickDialogEntry>
            {
                new("name", QuickDialogEntryType.ShortText,
                    Loc.GetString("slime-morph-save-prompt"),
                    Loc.GetString("slime-morph-save-placeholder"),
                    _selectedName),
            });

        dialog.OnConfirmed += results =>
        {
            if (results.TryGetValue("name", out var name) && !string.IsNullOrWhiteSpace(name))
                OnSaveAppearance?.Invoke(name.Trim());
        };
    }

