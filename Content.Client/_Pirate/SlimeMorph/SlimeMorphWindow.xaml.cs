        MimicButton.OnPressed += _ =>
        {
            if (_state?.CanMimic == true)
                OnMimic?.Invoke();
            else
                OnApply?.Invoke();
        };
        ForgetButton.OnPressed += _ =>
        {
            // Pirate: slime morph - same button forgets a studied target or deletes a saved look.
            if (_selectedSaved is { } saved)
                OnDeleteSaved?.Invoke(saved);
            else if (_selected is { } target)
                OnForget?.Invoke(target);
        };
        RevertButton.OnPressed += _ => OnRevert?.Invoke();
        ResetButton.OnPressed += _ => OnReset?.Invoke();

