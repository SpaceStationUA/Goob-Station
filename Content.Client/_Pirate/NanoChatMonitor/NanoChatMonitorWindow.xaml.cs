using System.Numerics;
using Content.Client.GameTicking.Managers;
using Content.Client.UserInterface.Controls;
using Content.Shared._Pirate.NanoChatMonitor;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Pirate.NanoChatMonitor;

/// <summary>
///     Holds no history of its own: it pulls pages from the server as the reader scrolls.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NanoChatMonitorWindow : FancyWindow
{
    private static readonly TimeSpan SeparatorGap = TimeSpan.FromMinutes(1);
    private static readonly Color SeparatorLineColor = Color.FromHex("#50597844");
    private static readonly Color SeparatorTextColor = Color.FromHex("#9ca6c2");

    private const float ScrollEdgeSlack = 24f;

    public event Action<ulong, int, bool, ulong>? OnRequestPage;

    public event Action<string>? OnRequestAttachment;

    public event Action<string>? OnPrintPhoto;

    public event Action<ulong>? OnPrintLog;

    /// <summary>
    ///     Requests network-wide deletion of the selected conversation.
    /// </summary>
    public event Action<ulong>? OnDeleteLog;

    private readonly ClientGameTicker _gameTicker;

    private readonly List<NanoChatMonitorConversationSummary> _conversations = new();
    private readonly List<NanoChatMonitorConversationEntry> _conversationEntries = new();

    private readonly Dictionary<int, NanoChatMonitorLogEntry> _loaded = new();

    private ulong? _selectedKey;
    private int _loadedStart;
    private int _loadedEnd;
    private int _totalCount;
    private ulong _revision;
    private ulong _lastRequestId;

    private bool _awaitingPage;

    private float? _prependAnchorHeight;

    private bool _scrollToBottom;

    private bool _stickToBottom;

    private readonly Dictionary<string, NanoChatMonitorAttachmentMessage> _attachments = new();
    private readonly Dictionary<string, Texture?> _attachmentTextures = new();

    private readonly HashSet<string> _requestedAttachments = new();

    private readonly List<NanoChatMonitorMessageRow> _rows = new();

    public NanoChatMonitorWindow()
    {
        RobustXamlLoader.Load(this);

        _gameTicker = IoCManager.Resolve<IEntityManager>().System<ClientGameTicker>();

        SearchBar.OnTextChanged += _ => RebuildConversationList();
        LatestButton.OnPressed += _ => RequestLatest();
        PrintLogButton.OnPressed += _ =>
        {
            if (_selectedKey is { } key)
                OnPrintLog?.Invoke(key);
        };

        // Erasing is irreversible and takes the peer servers with it, so it costs two presses.
        DeleteLogButton.OnPressed += _ =>
        {
            if (_selectedKey is not { } key)
                return;

            if (!_deleteArmed)
            {
                SetDeleteArmed(true);
                return;
            }

            SetDeleteArmed(false);
            OnDeleteLog?.Invoke(key);
        };
    }

    private bool _deleteArmed;

    private void SetDeleteArmed(bool armed)
    {
        _deleteArmed = armed;
        DeleteLogButton.Text = Loc.GetString(armed
            ? "nanochat-monitor-delete-log-confirm"
            : "nanochat-monitor-delete-log");
    }

    public void UpdateState(NanoChatMonitorUiState state)
    {
        _conversations.Clear();
        _conversations.AddRange(state.Conversations);

        RebuildConversationList();

        if (_selectedKey is not { } selected)
            return;

        var summary = _conversations.Find(c => c.Key == selected);

        // The open conversation can vanish under the reader, either because
        // someone erased it or because the peer server carrying it dropped off the network.
        if (summary.Key != selected)
        {
            ClearSelection();
            return;
        }

        var previousTotal = _totalCount;
        var previousRevision = _revision;
        _totalCount = summary.MessageCount;
        _revision = summary.Revision;
        UpdateCountLabel();

        if (_revision != previousRevision || _totalCount < previousTotal)
        {
            _loaded.Clear();
            _loadedStart = 0;
            _loadedEnd = 0;
            _prependAnchorHeight = null;
            _stickToBottom = false;
            MessageList.RemoveAllChildren();
            _rows.Clear();
            RequestLatest();
            return;
        }

        if (_totalCount == previousTotal || _loadedEnd < previousTotal)
            return;

        _stickToBottom = IsScrolledToBottom();
        RequestPage(Math.Max(0, _totalCount - NanoChatMonitorConstants.PageSize));
    }

    #region Conversation list

    private void RebuildConversationList()
    {
        var filter = SearchBar.Text.Trim().ToLowerInvariant();

        ConversationList.RemoveAllChildren();
        _conversationEntries.Clear();

        var shown = 0;

        foreach (var summary in _conversations)
        {
            if (filter.Length > 0 &&
                !NanoChatMonitorConversationEntry.BuildSearchText(summary).Contains(filter, StringComparison.Ordinal))
                continue;

            var entry = new NanoChatMonitorConversationEntry();
            entry.Update(summary, GetStationTime(summary.LastTimestamp), _selectedKey == summary.Key);
            entry.OnPressed += _ => SelectConversation(summary.Key);

            ConversationList.AddChild(entry);
            _conversationEntries.Add(entry);
            shown++;
        }

        NoConversationsLabel.Visible = shown == 0;
        NoConversationsLabel.Text = Loc.GetString(_conversations.Count == 0
            ? "nanochat-monitor-no-conversations"
            : "nanochat-monitor-no-matches");
    }

    private void ClearSelection()
    {
        _selectedKey = null;
        _totalCount = 0;
        _revision = 0;
        _lastRequestId++;
        _loaded.Clear();
        _loadedStart = 0;
        _loadedEnd = 0;

        foreach (var entry in _conversationEntries)
        {
            entry.SetSelected(false);
        }

        MessageList.RemoveAllChildren();
        _rows.Clear();

        HeaderLabel.Text = Loc.GetString("nanochat-monitor-select-conversation");
        UpdateCountLabel();
    }

    private void SelectConversation(ulong key)
    {
        _selectedKey = key;
        SetDeleteArmed(false);

        foreach (var entry in _conversationEntries)
        {
            entry.SetSelected(entry.ConversationKey == key);
        }

        var summary = _conversations.Find(c => c.Key == key);

        HeaderLabel.Text = Loc.GetString("nanochat-monitor-conversation-header",
            ("first", $"{summary.NameA} (#{summary.NumberA})"),
            ("second", $"{summary.NameB} (#{summary.NumberB})"));

        _totalCount = summary.MessageCount;
        _revision = summary.Revision;

        _loaded.Clear();
        _loadedStart = 0;
        _loadedEnd = 0;

        // Drop the stale conversation while the new page is loading.
        MessageList.RemoveAllChildren();
        _rows.Clear();

        UpdateCountLabel();
        RequestLatest();
    }

    #endregion

    #region Loading

    private void RequestLatest()
    {
        if (_selectedKey is not { } key)
            return;

        _awaitingPage = true;
        OnRequestPage?.Invoke(key, 0, true, ++_lastRequestId);
    }

    private void RequestPage(int start)
    {
        if (_selectedKey is not { } key)
            return;

        _awaitingPage = true;
        OnRequestPage?.Invoke(key, start, false, ++_lastRequestId);
    }

    public void HandlePage(NanoChatMonitorPageMessage message)
    {
        if (_selectedKey != message.ConversationKey || message.RequestId != _lastRequestId)
            return;

        _awaitingPage = false;

        if (_revision != message.Revision)
        {
            _revision = message.Revision;
            _loaded.Clear();
            _loadedStart = 0;
            _loadedEnd = 0;
            _prependAnchorHeight = null;
            _stickToBottom = false;
        }

        _totalCount = message.TotalCount;

        var pageStart = message.StartIndex;
        var pageEnd = pageStart + message.Entries.Count;
        var oldStart = _loadedStart;
        var oldEnd = _loadedEnd;

        var contiguous = oldEnd > oldStart && pageStart <= oldEnd && pageEnd >= oldStart;

        if (contiguous)
        {
            _loadedStart = Math.Min(oldStart, pageStart);
            _loadedEnd = Math.Max(oldEnd, pageEnd);
        }
        else
        {
            _loaded.Clear();
            _loadedStart = pageStart;
            _loadedEnd = pageEnd;
        }

        for (var i = 0; i < message.Entries.Count; i++)
        {
            _loaded[pageStart + i] = message.Entries[i];
        }

        if (!contiguous)
            _scrollToBottom = _loadedEnd >= _totalCount;
        else if (_loadedStart < oldStart)
            _prependAnchorHeight = MessageList.Height;
        else if (_stickToBottom)
            _scrollToBottom = true;

        _stickToBottom = false;

        Rebuild();
    }

    private void Rebuild()
    {
        MessageList.RemoveAllChildren();
        _rows.Clear();

        TimeSpan? previousTime = null;
        // Runs are tracked by which side spoke, since two redacted
        // participants share one displayed number.
        bool? previousSender = null;

        for (var i = _loadedStart; i < _loadedEnd; i++)
        {
            if (!_loaded.TryGetValue(i, out var entry))
                continue;

            var stationTime = GetStationTime(entry.Timestamp);

            if (previousTime == null || stationTime - previousTime.Value >= SeparatorGap)
            {
                AddTimeSeparator(stationTime);

                previousSender = null;
            }

            var row = new NanoChatMonitorMessageRow();
            // The first participant always takes the left hand side, so a conversation never flips.
            row.Update(entry, !entry.SenderIsA, previousSender != entry.SenderIsA);
            row.OnPrintPhoto += id => OnPrintPhoto?.Invoke(id);
            MessageList.AddChild(row);
            _rows.Add(row);

            if (entry.AttachmentId is { } attachmentId)
                LoadAttachment(row, attachmentId);

            previousTime = stationTime;
            previousSender = entry.SenderIsA;
        }

        UpdateCountLabel();
        MessageList.InvalidateMeasure();
        MessageScroll.InvalidateMeasure();
    }

    private void LoadAttachment(NanoChatMonitorMessageRow row, string attachmentId)
    {
        if (_attachments.TryGetValue(attachmentId, out var cached))
        {
            row.SetPhoto(cached, _attachmentTextures[attachmentId]);
            return;
        }

        if (!_requestedAttachments.Add(attachmentId))
            return;

        OnRequestAttachment?.Invoke(attachmentId);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_scrollToBottom)
        {
            MessageScroll.SetScrollValue(new Vector2(0, float.MaxValue));
            _scrollToBottom = false;
        }
        else if (_prependAnchorHeight is { } anchor)
        {
            var grew = MessageList.Height - anchor;
            if (grew > 0)
                MessageScroll.VScroll += grew;

            _prependAnchorHeight = null;
        }

        LatestButton.Visible = _selectedKey != null && !_awaitingPage && _loadedEnd < _totalCount;

        if (_selectedKey == null || _awaitingPage || _prependAnchorHeight != null || _scrollToBottom)
            return;

        if (MessageScroll.VScroll <= ScrollEdgeSlack && _loadedStart > 0)
            RequestPage(Math.Max(0, _loadedStart - NanoChatMonitorConstants.PageSize));
        else if (IsScrolledToBottom() && _loadedEnd < _totalCount)
            RequestPage(_loadedEnd);
    }

    private bool IsScrolledToBottom()
    {
        var viewport = MessageScroll.Height;
        var content = MessageList.Height;

        return content <= viewport || MessageScroll.VScroll + viewport >= content - ScrollEdgeSlack;
    }

    private void UpdateCountLabel()
    {
        CountLabel.Text = _selectedKey == null
            ? string.Empty
            : Loc.GetString("nanochat-monitor-message-count", ("count", _totalCount));

        PrintLogButton.Visible = _selectedKey != null && _totalCount > 0;
        DeleteLogButton.Visible = PrintLogButton.Visible;
    }

    private void AddTimeSeparator(TimeSpan stationTime)
    {
        MessageList.AddChild(new Control { MinSize = new Vector2(0, 6) });

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };

        row.AddChild(MakeSeparatorLine());
        row.AddChild(new Label
        {
            Text = stationTime.ToString(@"hh\:mm\:ss"),
            Margin = new Thickness(12, 0, 12, 0),
            StyleClasses = { "LabelSubText" },
            ModulateSelfOverride = SeparatorTextColor,
        });
        row.AddChild(MakeSeparatorLine());

        MessageList.AddChild(row);
        MessageList.AddChild(new Control { MinSize = new Vector2(0, 6) });
    }

    private static PanelContainer MakeSeparatorLine()
    {
        return new PanelContainer
        {
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            MinSize = new Vector2(0, 1),
            MaxSize = new Vector2(float.MaxValue, 1),
            PanelOverride = new StyleBoxFlat { BackgroundColor = SeparatorLineColor },
        };
    }

    private TimeSpan GetStationTime(TimeSpan timestamp)
    {
        var stationTime = timestamp - _gameTicker.RoundStartTimeSpan;
        return stationTime < TimeSpan.Zero ? TimeSpan.Zero : stationTime;
    }

    #endregion

    #region Attachments

    public void HandleAttachment(NanoChatMonitorAttachmentMessage message)
    {
        _attachments[message.AttachmentId] = message;
        if (!_attachmentTextures.ContainsKey(message.AttachmentId))
            _attachmentTextures[message.AttachmentId] = NanoChatMonitorMessageRow.LoadTexture(message.ImageData, message.AttachmentId);

        foreach (var row in _rows)
        {
            row.SetPhoto(message, _attachmentTextures[message.AttachmentId]);
        }
    }

    #endregion
}
