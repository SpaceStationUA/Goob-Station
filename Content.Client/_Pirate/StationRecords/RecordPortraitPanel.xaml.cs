namespace Content.Client._Pirate.StationRecords;

[GenerateTypedNameReferences]
public sealed partial class RecordPortraitPanel : BoxContainer
{
    [Dependency] private readonly IEntityManager _entManager = default!;
    [Dependency] private readonly IPrototypeManager _proto = default!;

    private const int TextureCacheLimit = 32;

    private readonly RecordPhotoComposerSystem _composer;
    private RecordPhotoStyle _photoStyle = RecordPhotoStyle.Civilian;

    public event Action<uint, byte[]?>? OnPrint;

    public event Action? OnUpload;

    public event Action<uint, byte[]>? OnStoreGenerated;

    private uint? _key;
    private MugshotLabel _label;
    private bool _canPrint;
    private EntityUid _previewDummy = EntityUid.Invalid;
    private uint? _previewKey;
    private byte[]? _shownImageData;

    private readonly HashSet<uint> _pendingGeneratedKeys = new();
    private readonly Dictionary<uint, (byte[] Data, Texture Texture)> _textureCache = new();
    private readonly Dictionary<uint, (HumanoidCharacterProfile Profile, string? Job, byte[] Data)> _generatedCache = new();

    private readonly Dictionary<uint, (string Source, byte[] Png)> _mugshotCache = new();
    private readonly Dictionary<uint, string> _composing = new();

    public RecordPortraitPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _composer = _entManager.System<RecordPhotoComposerSystem>();
        PortraitBackground.Texture = _composer.GetBackground(_photoStyle);

        PrintButton.OnPressed += _ => Print();
        UploadButton.OnPressed += _ => OnUpload?.Invoke();
        RecordConsoleSounds.Mute(PrintButton);
        RecordConsoleSounds.Mute(UploadButton);
    }

    public RecordPhotoStyle PhotoStyle
    {
        get => _photoStyle;
        set
        {
            _photoStyle = value;
            PortraitBackground.Texture = _composer.GetBackground(value);
            _mugshotCache.Clear();
        }
    }

    public void SetPortrait(uint key, RecordPortraitData? portrait, string? jobPrototype, string name, int age)
    {
        var image = portrait?.ImageData;
        var snapshot = portrait?.Snapshot;

        _key = key;
        var birthYear = portrait is { BirthYear: > 0 } ? portrait.BirthYear
            : age > 0 ? PirateStationCalendar.CurrentYear - age
            : 0;
        _label = new MugshotLabel(portrait?.Name ?? name, portrait?.Number ?? 0, birthYear);
        _canPrint = image is { Length: > 0 } || snapshot != null;

        if (image is { Length: > 0 } && portrait is { IsRender: false })
        {
            ClearPreview();
            if (TryShowImage(key, image))
                return;
        }

        ClearImage();

        var render = image is { Length: > 0 }
            ? image
            : TryGetGenerated(key, snapshot, jobPrototype, out var generated) ? generated : null;

        if (render != null)
        {
            ShowMugshot(key, render);
            return;
        }

        ShowPreview(key, snapshot, jobPrototype);
        EnsureGenerated(key, snapshot, jobPrototype);
    }

    public void ClearPortrait()
    {
        _key = null;
        _canPrint = false;
        ClearPreview();
        ClearImage();
        PortraitBackground.Visible = false;
    }

    public void SetEditable(bool editable)
    {
        PrintButton.Disabled = !editable || !_canPrint;
        UploadButton.Disabled = !editable;
    }

    public void SetButtonsVisible(bool visible)
    {
        PrintButton.Visible = visible;
        UploadButton.Visible = visible;
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            ClearPortrait();
            foreach (var (_, texture) in _textureCache.Values)
            {
                DisposeTexture(texture);
            }

            _textureCache.Clear();
            _generatedCache.Clear();
            _mugshotCache.Clear();
        }

        base.Dispose(disposing);
    }

    private async void Print()
    {
        if (_key is not { } key || !_canPrint)
            return;

        try
        {
            var image = _shownImageData;
            if (image is not { Length: > 0 } && await TryRenderWithRetry(_previewDummy) is { } render)
                image = await _composer.Compose(render, _photoStyle, _label);

            if (!Disposed)
                OnPrint?.Invoke(key, image);
        }
        catch (Exception ex)
        {
            Logger.ErrorS("records", $"Failed to prepare a record photo for printing: {ex}");
        }
    }

    private bool TryShowImage(uint key, byte[] imageData)
    {
        ClearImage();

        try
        {
            PortraitTexture.Texture = LoadTextureCached(key, imageData);
        }
        catch (Exception)
        {
            ClearImage();
            PortraitSprite.Visible = true;
            return false;
        }

        PortraitTexture.Visible = true;
        PortraitBackground.Visible = true;
        PortraitSprite.Visible = false;
        _shownImageData = [.. imageData];
        return true;
    }

    private void ClearImage()
    {
        _shownImageData = null;
        PortraitTexture.Texture = null;
        PortraitTexture.Visible = false;
    }

    private void ShowPreview(uint key, HumanoidCharacterProfile? snapshot, string? jobPrototype)
    {
        PortraitBackground.Visible = true;

        if (snapshot == null)
        {
            ClearPreview();
            return;
        }

        if (_previewKey == key && _entManager.EntityExists(_previewDummy))
            return;

        ClearPreview();

        if (!TryCreateDummy(snapshot, jobPrototype, out var dummy))
            return;

        _previewDummy = dummy;
        _previewKey = key;
        PortraitSprite.SetEntity(dummy);
        PortraitSprite.Visible = false;
    }

    private void ClearPreview()
    {
        if (_previewDummy != EntityUid.Invalid && _entManager.EntityExists(_previewDummy))
            _entManager.DeleteEntity(_previewDummy);

        _previewDummy = EntityUid.Invalid;
        _previewKey = null;
        PortraitSprite.SetEntity((EntityUid?) null);
        PortraitSprite.Visible = false;
    }

    private bool TryCreateDummy(HumanoidCharacterProfile snapshot, string? jobPrototype, out EntityUid dummy)
    {
        JobPrototype? job = null;
        if (!string.IsNullOrWhiteSpace(jobPrototype) && _proto.TryIndex<JobPrototype>(jobPrototype, out var indexedJob))
            job = indexedJob;

        dummy = UserInterfaceManager.GetUIController<LobbyUIController>().LoadProfileEntity(snapshot, job, true);
        if (dummy == EntityUid.Invalid || !_entManager.EntityExists(dummy))
            return false;

        _composer.DressForPhoto(dummy);
        return true;
    }

    private void EnsureGenerated(uint key, HumanoidCharacterProfile? snapshot, string? jobPrototype)
    {
        if (snapshot == null || !_pendingGeneratedKeys.Add(key))
            return;

        if (!TryCreateDummy(snapshot, jobPrototype, out var dummy))
        {
            _pendingGeneratedKeys.Remove(key);
            return;
        }

        _ = GenerateAsync(key, dummy, snapshot, jobPrototype);
    }

    private async Task GenerateAsync(uint key, EntityUid dummy, HumanoidCharacterProfile snapshot, string? jobPrototype)
    {
        try
        {
            // Keep the dummy alive until the asynchronous GPU readback completes.
            var image = await TryRenderWithRetry(dummy);
            if (Disposed)
                return;

            if (image is not { Length: > 0 })
            {
                if (_key == key && _previewKey == key)
                    PortraitSprite.Visible = true;

                return;
            }

            _generatedCache[key] = (snapshot, jobPrototype, image);

            if (_key == key)
                ShowMugshot(key, image);

            OnStoreGenerated?.Invoke(key, image);
        }
        finally
        {
            if (dummy != EntityUid.Invalid && _entManager.EntityExists(dummy))
                _entManager.DeleteEntity(dummy);

            _pendingGeneratedKeys.Remove(key);
        }
    }

    private void ShowMugshot(uint key, byte[] render)
    {
        var source = MugshotSource(render);
        if (_mugshotCache.TryGetValue(key, out var cached) && cached.Source == source)
        {
            ClearPreview();
            TryShowImage(key, cached.Png);
            return;
        }

        PortraitBackground.Visible = true;
        if (_composing.TryGetValue(key, out var pending) && pending == source)
            return;

        _composing[key] = source;
        _ = ComposeAsync(key, render, source);
    }

    private async Task ComposeAsync(uint key, byte[] render, string source)
    {
        try
        {
            var png = await _composer.Compose(render, _photoStyle, _label);
            if (Disposed || png == null || !_composing.TryGetValue(key, out var wanted) || wanted != source)
                return;

            _mugshotCache[key] = (source, png);
            if (_key == key && MugshotSource(render) == source)
            {
                ClearPreview();
                TryShowImage(key, png);
            }
        }
        catch (Exception ex)
        {
            Logger.ErrorS("records", $"Failed to compose a record mugshot: {ex}");
        }
        finally
        {
            if (_composing.TryGetValue(key, out var wanted) && wanted == source)
                _composing.Remove(key);
        }
    }

    private string MugshotSource(byte[] render)
    {
        var hash = 17;
        foreach (var b in render)
        {
            hash = unchecked(hash * 31 + b);
        }

        return $"{_photoStyle}|{_label.Name}|{_label.Number}|{_label.BirthYear}|{render.Length}|{hash}";
    }

    private bool TryGetGenerated(uint key, HumanoidCharacterProfile? snapshot, string? job, out byte[] imageData)
    {
        imageData = default!;
        if (snapshot == null
            || !_generatedCache.TryGetValue(key, out var cached)
            || cached.Job != job
            || !cached.Profile.MemberwiseEquals(snapshot))
        {
            return false;
        }

        imageData = cached.Data;
        return true;
    }

    private async Task<byte[]?> TryRenderWithRetry(EntityUid dummy, int attempts = 4, int delayMs = 100)
    {
        for (var attempt = 0; attempt < attempts; attempt++)
        {
            var image = await TryRender(dummy);
            if (image is { Length: > 0 })
                return image;

            if (attempt < attempts - 1)
                await Task.Delay(delayMs);
        }

        return null;
    }

    private async Task<byte[]?> TryRender(EntityUid dummy)
    {
        if (dummy == EntityUid.Invalid || !_entManager.EntityExists(dummy))
            return null;

        try
        {
            return await _composer.RenderEntity(dummy);
        }
        catch (Exception)
        {
            return null;
        }
    }

    private Texture LoadTextureCached(uint key, byte[] imageData)
    {
        if (_textureCache.TryGetValue(key, out var cached) && cached.Data.AsSpan().SequenceEqual(imageData))
            return cached.Texture;

        Texture texture;
        using (var stream = new MemoryStream(imageData, writable: false))
        {
            texture = Texture.LoadFromPNGStream(stream, $"record-portrait-{key}");
        }

        if (_textureCache.Remove(key, out var replaced))
            DisposeTexture(replaced.Texture);

        if (_textureCache.Count >= TextureCacheLimit)
        {
            var evicted = _textureCache.Keys.First();
            DisposeTexture(_textureCache[evicted].Texture);
            _textureCache.Remove(evicted);
        }

        _textureCache[key] = ([.. imageData], texture);
        return texture;
    }

    private static void DisposeTexture(Texture texture)
    {
        if (texture is OwnedTexture owned)
            owned.Dispose();
    }
}
