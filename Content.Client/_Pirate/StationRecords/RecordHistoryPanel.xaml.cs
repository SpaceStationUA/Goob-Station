using System.Numerics;
using Content.Shared._Pirate;
using Content.Shared._Pirate.StationRecords;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Pirate.StationRecords;
[GenerateTypedNameReferences]
public sealed partial class RecordHistoryPanel : BoxContainer
{
    public event Action<string>? OnAddNote;
    public event Action<uint>? OnDeleteEntry;
    public event Action? OnPrint;

    private static readonly ResPath LogIcons = new("_Pirate/Interface/record_log_icons.rsi");
    private static readonly ResPath SecurityIcons = new("Interface/Misc/security_icons.rsi");
    private static readonly ResPath PsionicsIcons = new("_EinsteinEngines/Interface/Misc/psionics_icons.rsi");
    private static readonly ResPath JobIcons = new("Interface/Misc/job_icons.rsi");
    private static readonly Color NoteColor = Color.FromHex("#8EAAD4");
    private static readonly Color BackgroundColor = Color.FromHex("#EFB04A");

    private readonly SpriteSystem _sprite;
    public RecordLogBook Book { get; set; } = RecordLogBook.Crew;
    private RecordNoteDialog? _dialog;
    private uint? _recordKey;
    private IReadOnlyList<RecordLogEntry>? _log;
    private bool _canEdit;
    private string _query = string.Empty;
    private bool _pdaLayout;

    public bool PdaLayout
    {
        get => _pdaLayout;
        set
        {
            _pdaLayout = value;
            PrintButton.Visible = !value;
            if (value)
                AddNoteButton.StyleClasses.Remove("OpenLeft");
            else if (!AddNoteButton.StyleClasses.Contains("OpenLeft"))
                AddNoteButton.StyleClasses.Add("OpenLeft");
        }
    }

    public RecordHistoryPanel()
    {
        RobustXamlLoader.Load(this);
        _sprite = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>();
        AddNoteButton.OnPressed += _ => OpenAddDialog();
        PrintButton.OnPressed += _ => OnPrint?.Invoke();
        RecordConsoleSounds.Mute(PrintButton);
    }

    public void UpdateLog(uint recordKey, string name, IReadOnlyList<RecordLogEntry>? log, bool canEdit)
    {
        if (_recordKey != recordKey)
        {
            _recordKey = recordKey;
            _dialog?.Close();
        }

        PersonName.Text = name;
        AddNoteButton.Visible = canEdit || _pdaLayout;
        AddNoteButton.Disabled = !canEdit;
        PrintButton.Visible = canEdit && !_pdaLayout;
        _log = log == null ? null : RecordLogOrder.ForDisplay(log);
        _canEdit = canEdit;
        Rebuild();
    }
    public void SetQuery(string query)
    {
        query = query.Trim();
        if (query == _query)
            return;

        _query = query;
        Rebuild();
    }

    public void CloseDialog()
    {
        _dialog?.Close();
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
            _dialog?.Close();

        base.Dispose(disposing);
    }

    private void Rebuild()
    {
        Entries.RemoveAllChildren();

        var shown = 0;
        if (_log != null)
        {
            foreach (var entry in _log)
            {
                var look = Describe(entry);
                if (!Matches(entry, look.Title))
                    continue;

                Entries.AddChild(MakeEntry(entry, look));
                shown++;
            }
        }

        NoEntries.Text = Loc.GetString(_log is { Count: > 0 } ? "records-log-no-matches" : "records-log-empty");
        NoEntries.Visible = shown == 0;
    }

    private bool Matches(RecordLogEntry entry, string title)
    {
        if (_query.Length == 0)
            return true;

        return Contains(title)
            || Contains(entry.Message)
            || Contains(AuthorName(entry))
            || Contains(entry.AuthorTitle)
            || Contains(entry.StationName)
            || entry.Kind != RecordLogKind.Background && Contains(FormatTime(entry.Time));

        bool Contains(string? text) => text != null && text.Contains(_query, StringComparison.CurrentCultureIgnoreCase);
    }

    private Control MakeEntry(RecordLogEntry entry, (string Title, Color Color, SpriteSpecifier Icon) look)
    {
        var (title, color, icon) = look;

        var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        header.AddChild(new TextureRect
        {
            Texture = _sprite.Frame0(icon),
            TextureScale = new Vector2(2f, 2f),
            VerticalAlignment = Control.VAlignment.Center,
        });
        header.AddChild(new Label { Text = title, FontColorOverride = color, ClipText = true, HorizontalExpand = true });
        // The shift-start timestamp positions the HR file; it isn't a date anyone wrote down.
        if (entry.Kind != RecordLogKind.Background)
            header.AddChild(new Label { Text = FormatTime(entry.Time), FontColorOverride = Color.DarkGray });

        if (_canEdit && entry.Kind != RecordLogKind.Background)
        {
            var delete = new Button
            {
                Text = Loc.GetString("records-log-delete"),
                StyleClasses = { "ButtonColorRed" },
                VerticalAlignment = Control.VAlignment.Center,
            };
            var id = entry.Id;
            delete.OnPressed += _ => OnDeleteEntry?.Invoke(id);
            header.AddChild(delete);
        }

        var body = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 2,
            Margin = new Thickness(8, 6),
        };
        body.AddChild(header);

        var author = AuthorName(entry);
        if (!string.IsNullOrWhiteSpace(entry.AuthorTitle))
            author = $"{author} ({entry.AuthorTitle})";
        body.AddChild(Text(author, Color.DarkGray));

        if (!string.IsNullOrWhiteSpace(entry.StationName))
            body.AddChild(Text(Loc.GetString("records-log-station", ("station", entry.StationName)), Color.Gray));

        if (!string.IsNullOrWhiteSpace(entry.Message))
            body.AddChild(Text(entry.Message, null));

        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#1B1B21"),
                BorderColor = color.WithAlpha(0.6f),
                BorderThickness = new Thickness(3, 0, 0, 0),
            },
        };
        panel.AddChild(body);
        return panel;
    }

    private static RichTextLabel Text(string text, Color? color)
    {
        var message = new FormattedMessage();
        if (color is { } c)
            message.PushColor(c);
        message.AddText(text);
        if (color != null)
            message.Pop();

        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMessage(message);
        return label;
    }

    private static string AuthorName(RecordLogEntry entry)
    {
        return entry.AuthorName
            ?? Loc.GetString(entry.Kind == RecordLogKind.Background ? "records-log-hr-author" : "records-log-unknown-author");
    }
    private (string Title, Color Color, SpriteSpecifier Icon) Describe(RecordLogEntry entry)
    {
        switch (entry.Kind)
        {
            case RecordLogKind.Background:
                return (entry.Topic ?? Loc.GetString("records-log-kind-background"), BackgroundColor,
                    new SpriteSpecifier.Rsi(LogIcons, "hr_file"));

            case RecordLogKind.StatusChange:
                var title = entry.Topic ?? Loc.GetString("records-log-kind-status-change");
                var (color, icon) = Book == RecordLogBook.Psionics
                    ? PsionicsStatusLook(entry.Status)
                    : SecurityStatusLook(entry.Status);
                return (title, color, icon);

            default:
                return (Loc.GetString("records-log-kind-note"), NoteColor, new SpriteSpecifier.Rsi(LogIcons, "note"));
        }
    }
    private static (Color, SpriteSpecifier) SecurityStatusLook(string? status)
    {
        var (state, color) = status switch
        {
            "Suspected" => ("hud_suspected", "#33CCCC"),
            "Wanted" => ("hud_wanted", "#FF4A4A"),
            "Hostile" => ("hud_hostile", "#D23C3C"),
            "Detained" => ("hud_incarcerated", "#C9985A"),
            "Paroled" => ("hud_paroled", "#8FC72A"),
            "Discharged" => ("hud_discharged", "#4FA3FF"),
            "Eliminated" => ("hud_eliminated", "#8A8A8A"),
            "Search" => ("hud_search", "#5FD3D3"),
            "Perma" => ("hud_perma", "#A0A0AA"),
            "Dangerous" => ("hud_dangerous", "#FF7A5C"),
            "Demote" => ("hud_demote", "#FF6040"),
            _ => (null, "#C8C8C8"),
        };

        return (Color.FromHex(color), state == null
            ? new SpriteSpecifier.Rsi(JobIcons, "Unknown")
            : new SpriteSpecifier.Rsi(SecurityIcons, state));
    }

    private static (Color, SpriteSpecifier) PsionicsStatusLook(string? status)
    {
        var (state, color) = status switch
        {
            "Suspected" => ("hud_suspected", "#E3A6DB"),
            "Registered" => ("hud_registered", "#C96DBF"),
            "Abusing" => ("hud_abusing", "#FF5FA2"),
            _ => (null, "#C8C8C8"),
        };

        return (Color.FromHex(color), state == null
            ? new SpriteSpecifier.Rsi(JobIcons, "Unknown")
            : new SpriteSpecifier.Rsi(PsionicsIcons, state));
    }
    private static string FormatTime(DateTime utc)
    {
        var local = DateTime.SpecifyKind(utc, DateTimeKind.Utc).ToLocalTime();
        return $"{local.Day:00}/{local.Month:00}/{PirateStationCalendar.CurrentYear:0000} {local.Hour:00}:{local.Minute:00}";
    }

    private void OpenAddDialog()
    {
        if (_dialog != null)
        {
            _dialog.MoveToFront();
            return;
        }

        _dialog = new RecordNoteDialog();
        _dialog.OnConfirmed += text => OnAddNote?.Invoke(text);
        _dialog.OnClose += () => { _dialog = null; };
        _dialog.OpenCentered();
        RecordConsoleSounds.AttachDialog(this, _dialog);
    }
}
