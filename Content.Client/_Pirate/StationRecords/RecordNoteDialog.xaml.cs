using Content.Client.UserInterface.Controls;
using Content.Shared._Pirate.StationRecords;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Pirate.StationRecords;

[GenerateTypedNameReferences]
public sealed partial class RecordNoteDialog : FancyWindow
{
    public event Action<string>? OnConfirmed;

    public RecordNoteDialog()
    {
        RobustXamlLoader.Load(this);

        NoteInput.Placeholder = new Rope.Leaf(Loc.GetString("records-log-note-prompt"));
        NoteInput.OnTextChanged += _ => UpdateCounter();
        AddButton.OnPressed += _ => Confirm();
        CancelButton.OnPressed += _ => Close();
        UpdateCounter();
    }

    protected override void Opened()
    {
        base.Opened();
        NoteInput.GrabKeyboardFocus();
    }

    private string CurrentText()
    {
        return RecordLogNotes.Sanitize(Rope.Collapse(NoteInput.TextRope));
    }

    private void UpdateCounter()
    {
        var length = CurrentText().Length;
        var tooLong = length > RecordLogNotes.MaxLength;
        Counter.Text = $"{length}/{RecordLogNotes.MaxLength}";
        Counter.FontColorOverride = tooLong ? Color.FromHex("#FF4A4A") : Color.DarkGray;
        AddButton.Disabled = length == 0 || tooLong;
    }

    private void Confirm()
    {
        var text = CurrentText();
        if (text.Length == 0 || text.Length > RecordLogNotes.MaxLength)
            return;

        OnConfirmed?.Invoke(text);
        Close();
    }
}
