using System.Linq;
using Content.Client.Parallax.Data;
using Content.Client.Stylesheets.Palette;
using Content.Client.UserInterface.Controls;
using Content.Shared._Pirate.Journey;
using Content.Shared._Pirate.Shuttles.Warp;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Prototypes;

namespace Content.Client._Pirate.Shuttles.Warp;

[GenerateTypedNameReferences]
public sealed partial class WarpDriveWindow : FancyWindow
{
    private WarpDriveBoundUserInterface? _bui;

    // Set on press and cleared by the next state push. Without it, a second press lands before the
    // state has caught up and aborts the spool the first press started.
    private bool _awaitingToggle;

    // Sector IDs in the same order as the course picker rows.
    private readonly List<string> _courseIds = new();

    public WarpDriveWindow()
    {
        RobustXamlLoader.Load(this);

        ToggleButton.OnPressed += _ =>
        {
            _awaitingToggle = true;
            ToggleButton.Disabled = true;
            _bui?.Toggle();
        };
        JumpButton.OnPressed += _ => _bui?.Jump();
        CourseOptions.OnItemSelected += args => SelectCourse(args.Id);
        FillCourses();
    }

    public void UpdateWindow(WarpDriveBoundUserInterface bui)
    {
        _bui = bui;
        EntityView.SetEntity(bui.Owner);
    }

    public void UpdateState(WarpDriveBuiState state)
    {
        _awaitingToggle = false;
        StateLabel.Text = Loc.GetString(state.DriveState switch
        {
            WarpDriveState.Idle => "warp-drive-window-state-idle",
            WarpDriveState.Spooling => "warp-drive-window-state-spooling",
            WarpDriveState.Engaged => "warp-drive-window-state-engaged",
            WarpDriveState.InTransit => "warp-drive-window-state-in-transit",
            _ => throw new ArgumentOutOfRangeException()
        });

        // The colour repeats the text on purpose: during a countdown people glance at the window.
        StateLabel.FontColorOverride = state.DriveState switch
        {
            WarpDriveState.Idle => Palettes.Neutral.Base,
            WarpDriveState.Spooling => Palettes.Status.Warning,
            WarpDriveState.Engaged => Palettes.Status.Good,
            WarpDriveState.InTransit => Palettes.Status.Good,
            _ => Palettes.Neutral.Base
        };

        UpdatePower(state);
        UpdateGrid(state);
        UpdateSystem(state);
        UpdateJump(state);
        UpdateSpool(state);
        UpdateHeat(state);
        UpdateTimers(state);
        UpdateButton(state);
        UpdateCourse(state);
    }

    /// <summary>
    ///     Fills the course picker. Each system is marked quiet or loud, since the console knows the
    ///     prototypes but not the round's gate. The server refuses gated picks on the notice line.
    /// </summary>
    private void FillCourses()
    {
        var prototypes = IoCManager.Resolve<IPrototypeManager>();
        _courseIds.Clear();
        CourseOptions.Clear();

        var sectors = prototypes.EnumeratePrototypes<JourneySectorPrototype>()
            .OrderBy(s => Loc.GetString(s.Name))
            .ToList();
        for (var i = 0; i < sectors.Count; i++)
        {
            var sector = sectors[i];
            _courseIds.Add(sector.ID);
            var mood = sector.MajorEvents.Count == 0
                ? Loc.GetString("warp-drive-window-course-quiet")
                : Loc.GetString("warp-drive-window-course-loud");
            CourseOptions.AddItem($"{Loc.GetString(sector.Name)} ({mood})", i);
        }
    }

    private void SelectCourse(int row)
    {
        if (row < 0 || row >= _courseIds.Count)
            return;

        _bui?.SetCourse(_courseIds[row]);
        ShowCourseDescription(_courseIds[row]);
    }

    private void UpdateCourse(WarpDriveBuiState state)
    {
        // Follow the server's course without fighting the player's scrolling: reselect only when the
        // confirmed course differs from the row shown.
        var row = _courseIds.IndexOf(state.CourseSector);
        if (row >= 0 && CourseOptions.SelectedId != row)
            CourseOptions.SelectId(row);

        if (row >= 0)
            ShowCourseDescription(state.CourseSector);

        NoticeLabel.Visible = !string.IsNullOrEmpty(state.Notice);
        NoticeLabel.Text = state.Notice;
        NoticeLabel.FontColorOverride = Palettes.Status.Critical;
    }

    private void ShowCourseDescription(string sectorId)
    {
        var prototypes = IoCManager.Resolve<IPrototypeManager>();
        if (!prototypes.TryIndex<JourneySectorPrototype>(sectorId, out var sector)
            || !prototypes.TryIndex<ParallaxPrototype>(sector.Parallax, out var parallax)
            || parallax.SectorDescription == string.Empty)
        {
            CourseDescription.SetMessage(string.Empty);
            return;
        }

        CourseDescription.SetMessage(Loc.GetString(parallax.SectorDescription));
    }

    /// <summary>
    ///     Shows what the grid supplies against what the drive asks for. A shortfall is the first sign
    ///     that the drive is about to drop, so it is spelled out in text.
    /// </summary>
    private void UpdatePower(WarpDriveBuiState state)
    {
        PowerLabel.Text = Loc.GetString("warp-drive-window-power-value",
            ("draw", state.PowerDraw),
            ("max", state.PowerDrawMax));

        if (!state.Powered)
        {
            PowerLabel.Text = Loc.GetString("warp-drive-window-power-none");
            PowerLabel.FontColorOverride = Palettes.Status.Critical;
            return;
        }

        // Demand above supply means the grid cannot keep up, which only shows while drawing hard.
        var starving = state.PowerDrawMax > 0f && state.PowerDraw + 1f < state.PowerDrawMax;
        PowerLabel.FontColorOverride = starving ? Palettes.Status.Critical : Palettes.Status.Good;
    }

    /// <summary>
    ///     Grid headroom for a spool: supply against need. Green means the button will work.
    /// </summary>
    private void UpdateGrid(WarpDriveBuiState state)
    {
        GridLabel.Text = Loc.GetString("warp-drive-window-grid-value",
            ("free", state.GridSupply),
            ("need", state.GridNeed));
        GridLabel.FontColorOverride = state.SpoolReady ? Palettes.Status.Good : Palettes.Status.Critical;
    }

    /// <summary>
    ///     The current system, if a journey rule is live. Red when none, since a spool then burns time for nothing.
    /// </summary>
    private void UpdateSystem(WarpDriveBuiState state)
    {
        var live = !string.IsNullOrEmpty(state.CurrentSystem);
        SystemLabel.Text = live
            ? state.CurrentSystem
            : Loc.GetString("warp-drive-window-system-none");
        SystemLabel.FontColorOverride = live ? Palettes.Status.Good : Palettes.Status.Critical;
    }

    /// <summary>
    ///     The jump trigger. Lit only with a live field, a course and a journey; the server refuses
    ///     every other combination.
    /// </summary>
    private void UpdateJump(WarpDriveBuiState state)
    {
        switch (state.DriveState)
        {
            case WarpDriveState.Engaged:
                JumpButton.Text = Loc.GetString("warp-drive-window-jump");
                JumpButton.Disabled = state.CourseSector == string.Empty
                    || string.IsNullOrEmpty(state.CurrentSystem);
                break;

            case WarpDriveState.InTransit:
                JumpButton.Text = Loc.GetString("warp-drive-window-in-transit");
                JumpButton.Disabled = true;
                break;

            default:
                JumpButton.Text = Loc.GetString("warp-drive-window-jump");
                JumpButton.Disabled = true;
                break;
        }
    }

    private void UpdateSpool(WarpDriveBuiState state)
    {
        var spooling = state.DriveState == WarpDriveState.Spooling;
        SpoolBar.Value = state.SpoolProgress;
        SpoolText.Text = spooling
            ? Loc.GetString("warp-drive-window-spool-value", ("pct", (int) (state.SpoolProgress * 100f)))
            : Loc.GetString("warp-drive-window-none");

        // A finished or unstarted spool is not a problem, so it stays neutral rather than green.
        SpoolText.FontColorOverride = spooling ? Palettes.Status.Warning : Palettes.Neutral.Base;
    }

    /// <summary>
    ///     Core heat. This is the bar worth watching, because it is the one that ends the round.
    /// </summary>
    private void UpdateHeat(WarpDriveBuiState state)
    {
        HeatBar.Value = state.Heat;
        HeatText.Text = Loc.GetString("warp-drive-window-heat-value", ("pct", (int) (state.Heat * 100f)));

        HeatText.FontColorOverride = state.Heat switch
        {
            < 0.4f => Palettes.Neutral.Base,
            < 0.75f => Palettes.Status.Warning,
            _ => Palettes.Status.Critical
        };
    }

    private void UpdateTimers(WarpDriveBuiState state)
    {
        if (state.StabilityRemaining >= 0f)
        {
            StabilityLabel.Text = Loc.GetString("warp-drive-window-stability-value",
                ("time", FormatDuration(state.StabilityRemaining)));
            StabilityLabel.FontColorOverride = state.StabilityRemaining < 10f
                ? Palettes.Status.Critical
                : Palettes.Status.Warning;
        }
        else
        {
            StabilityLabel.Text = Loc.GetString("warp-drive-window-none");
            StabilityLabel.FontColorOverride = Palettes.Neutral.Base;
        }

        if (state.CoolDownRemaining > 0f)
        {
            CoolDownLabel.Text = Loc.GetString("warp-drive-window-cooldown-value",
                ("time", FormatDuration(state.CoolDownRemaining)));
            CoolDownLabel.FontColorOverride = Palettes.Status.Warning;
        }
        else
        {
            CoolDownLabel.Text = Loc.GetString("warp-drive-window-none");
            CoolDownLabel.FontColorOverride = Palettes.Neutral.Base;
        }
    }

    /// <summary>
    ///     The one control. Its label says what pressing it does, which is not always what the drive
    ///     allows: a cooling drive offers "spool up" and quietly refuses it. While a press is in flight
    ///     the button stays disabled.
    /// </summary>
    private void UpdateButton(WarpDriveBuiState state)
    {
        if (_awaitingToggle)
        {
            ToggleButton.Disabled = true;
            return;
        }

        switch (state.DriveState)
        {
            case WarpDriveState.Idle:
                var cooling = state.CoolDownRemaining > 0f;
                ToggleButton.Text = cooling
                    ? Loc.GetString("warp-drive-window-cooling")
                    : Loc.GetString("warp-drive-window-spool-up");
                ToggleButton.Disabled = cooling || !state.SpoolReady;
                break;

            case WarpDriveState.Spooling:
            case WarpDriveState.Engaged:
                ToggleButton.Text = Loc.GetString("warp-drive-window-shut-down");
                ToggleButton.Disabled = false;
                break;

            default:
                ToggleButton.Text = Loc.GetString("warp-drive-window-in-transit");
                ToggleButton.Disabled = true;
                break;
        }
    }

    /// <summary>
    ///     Formats seconds as m:ss, dropping the sub-second part.
    /// </summary>
    /// <remarks>
    ///     <c>TimeSpan.ToString()</c> prints a 2 minute 16 second cooldown as "0:02:16.6667175", which
    ///     is unreadable and visibly jitters as it counts down.
    /// </remarks>
    private static string FormatDuration(float seconds)
    {
        var total = (int) Math.Max(0f, seconds);
        return $"{total / 60:00}:{total % 60:00}";
    }
}
