using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Pirate.Revolution;
using Content.Shared.Eui;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.RichText;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Pirate.Revolution;

[GenerateTypedNameReferences]
public sealed partial class PirateRevolutionOrderWindow : FancyWindow
{
    private static readonly Type[] AnnouncementTags = { typeof(FontTag), typeof(BoldTag) };

    private List<RevOrderOption> _options = new();
    private readonly List<(ContainerButton Button, RichTextLabel Caption)> _orderButtons = new();
    private readonly List<CheckBox> _crewButtons = new();
    private RevOrderPreview? _preview;
    private ConfirmButton _applyButton = default!;
    private int _revision;
    private int _option = -1;
    private int _group = -1;
    private bool _pending;
    private RevOrderActivityState? _activity;
    private bool _showHistory;

    public event Action<EuiMessageBase>? OnRequest;

    private RevOrderOption? SelectedOrder => _option >= 0 ? _options[_option] : null;
    private RevOrderGroup? SelectedGroup => _group >= 0 ? SelectedOrder?.Groups[_group] : null;

    public PirateRevolutionOrderWindow()
    {
        RobustXamlLoader.Load(this);

        Amount.InitDefaultButtons();
        Fine.IsValid = RevOrderTaxFine.IsValid;
        // The client sandbox blocks compiler-generated collection calls.
        Fine.SetButtons(new List<int> { -RevOrderTaxFine.Step }, new List<int> { RevOrderTaxFine.Step });
        Fine.OverrideValue(RevOrderTaxFine.Default);
        FineRange.Text = Loc.GetString("pirate-rev-ui-fine-range", ("min", RevOrderTaxFine.Min), ("max", RevOrderTaxFine.Max));
        OrderSearch.OnTextChanged += _ =>
        {
            UpdateOrderSearch();
            OrderScroll.VScroll = 0;
        };
        TargetSelect.OnItemSelected += args => SelectGroup(args.Id);
        PickCrew.OnToggled += _ => UpdateCrewSelection();
        RefreshButton.OnPressed += _ => Request(new RevOrderRefresh(_revision));
        RandomButton.OnPressed += _ => Randomize();
        ReviewButton.OnPressed += _ => RequestReview();
        AutomaticOrders.OnToggled += args =>
        {
            if (_activity is not { } activity)
                return;

            AutomaticOrders.Disabled = true;
            OnRequest?.Invoke(new RevOrderSetAutomatic(activity.Round, args.Pressed));
        };
        AutomaticOrders.ToolTip = Loc.GetString("pirate-rev-ui-automatic-tooltip");
        HistoryButton.OnPressed += _ => ShowHistory(!_showHistory);
        HistoryNewer.OnPressed += _ => ReadHistory(-1);
        HistoryOlder.OnPressed += _ => ReadHistory(1);
        BackButton.OnPressed += _ =>
        {
            if (_pending)
                return;

            _preview = null;
            UpdatePageVisibility();
        };
        Template.OnTextChanged += _ => UpdatePreview();
        ResetConfirmation();
        UpdateConfiguration();
    }

    public void SetState(PirateRevolutionOrderEuiState state)
    {
        _revision = state.Revision;
        _pending = false;
        SetStatus(state.Status);
        if (state.Preview is { } preview)
        {
            UpdateConfiguration();
            var newPreview = _preview == null;
            _preview = preview;
            UpdatePageVisibility();
            Template.Editable = true;
            BackButton.Disabled = false;
            if (newPreview)
                SetPreview(preview);

            ResetConfirmation();
            UpdatePreview();
            return;
        }

        _preview = null;
        UpdatePageVisibility();
        var oldId = SelectedOrder?.Id;
        _options = state.Options;
        BuildOrderList();
        var order = _options.FindIndex(option => option.Id == oldId && option.Unavailable == null);
        if (order < 0)
            order = _options.FindIndex(option => option.Unavailable == null);
        SelectOrder(order);
    }

    public void SetActivity(RevOrderActivityState activity)
    {
        var pageChanged = _activity?.Page != activity.Page || _activity?.Round != activity.Round;
        _activity = activity;
        AutomaticOrders.Pressed = activity.Automatic;
        AutomaticOrders.Disabled = false;
        RevolutionStatus.Text = Loc.GetString(activity.RuleActive ? "pirate-rev-ui-revolution-present" : "pirate-rev-ui-revolution-absent");
        RevolutionStatus.Visible = true;
        if (_showHistory)
            BuildHistory(pageChanged);
    }

    private void ShowHistory(bool show)
    {
        _showHistory = show;
        HistoryButton.Text = Loc.GetString(show ? "pirate-rev-ui-history-back" : "pirate-rev-ui-history");
        UpdatePageVisibility();
        if (show)
        {
            if (_preview != null)
            {
                ResetConfirmation();
                UpdatePreview();
            }

            BuildHistory(true);
        }
    }

    private void UpdatePageVisibility()
    {
        History.Visible = _showHistory;
        Configuration.Visible = !_showHistory && _preview == null;
        Review.Visible = !_showHistory && _preview != null;
    }

    private void ReadHistory(int offset)
    {
        if (_activity is not { } activity)
            return;

        HistoryNewer.Disabled = HistoryOlder.Disabled = true;
        OnRequest?.Invoke(new RevOrderReadHistory(activity.Page + offset));
    }

    private void BuildHistory(bool resetScroll)
    {
        if (_activity is not { } activity)
            return;

        HistoryEmpty.Visible = activity.Entries.Count == 0;
        HistoryNavigation.Visible = activity.LastPage > 0;
        HistoryNewer.Disabled = activity.Page == 0;
        HistoryOlder.Disabled = activity.Page == activity.LastPage;
        HistoryPage.Text = Loc.GetString("pirate-rev-ui-history-page",
            ("page", activity.Page + 1), ("total", activity.LastPage + 1));

        HistoryEntries.DisposeAllChildren();
        foreach (var entry in activity.Entries)
        {
            var time = entry.RoundTime;
            var source = entry.Source switch
            {
                RevOrderSource.Automatic => Loc.GetString("pirate-rev-ui-history-automatic"),
                RevOrderSource.Admin => Loc.GetString("pirate-rev-ui-history-admin", ("admin", entry.Admin ?? string.Empty)),
                _ => Loc.GetString("pirate-rev-ui-history-console"),
            };
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(8) };
            row.AddChild(new Label
            {
                Text = $"{(int) time.TotalHours:00}:{time.Minutes:00}:{time.Seconds:00}  ·  {source}",
                StyleClasses = { "LabelSubText" },
                ClipText = true,
            });
            var title = new RichTextLabel();
            SetText(title, entry.Order, Color.Gold);
            row.AddChild(title);
            var body = new RichTextLabel();
            SetText(body, entry.Announcement);
            row.AddChild(body);
            HistoryEntries.AddChild(new PanelContainer { StyleClasses = { "PanelDark" }, Children = { row } });
        }

        if (resetScroll)
            HistoryScroll.VScrollTarget = 0;
    }

    private void BuildOrderList()
    {
        OrderList.DisposeAllChildren();
        _orderButtons.Clear();
        for (var index = 0; index < _options.Count; index++)
        {
            var option = _options[index];
            var caption = new RichTextLabel { Margin = new Thickness(3, 0) };
            SetText(caption, option.Name);
            var button = new ContainerButton
            {
                ToolTip = option.Unavailable == null ? option.Name : $"{option.Name}\n{option.Unavailable}",
                SetHeight = 56,
                RectClipContent = true,
                ToggleMode = true,
                StyleClasses = { ContainerButton.StyleClassButton },
                Children = { caption },
            };
            var id = index;
            button.OnPressed += _ => SelectOrder(id);
            _orderButtons.Add((button, caption));
            OrderList.AddChild(button);
        }
        UpdateOrderSearch();
    }

    private void UpdateOrderSearch()
    {
        var search = OrderSearch.Text.Trim();
        var hasMatch = false;
        for (var i = 0; i < _orderButtons.Count; i++)
        {
            var option = _options[i];
            var matches = option.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase)
                || option.Id.Contains(search, StringComparison.OrdinalIgnoreCase);
            _orderButtons[i].Button.Visible = matches;
            hasMatch |= matches;
        }

        NoOrderMatches.Visible = search.Length > 0 && !hasMatch;
    }

    private void SelectOrder(int index)
    {
        if (_pending)
            return;

        _option = index;
        for (var i = 0; i < _orderButtons.Count; i++)
            _orderButtons[i].Button.Pressed = i == index;

        TargetSelect.Clear();
        var groups = SelectedOrder?.Groups;
        if (groups != null)
        {
            for (var i = 0; i < groups.Count; i++)
            {
                if (groups[i].Department != null)
                    TargetSelect.AddItem(groups[i].Name, i);
            }
        }

        OrderName.Text = SelectedOrder?.Name;
        OrderName.ToolTip = SelectedOrder?.Name;
        Fine.OverrideValue(RevOrderTaxFine.Default);
        SelectGroup(groups is { Count: > 0 } ? 0 : -1);
    }

    private void SelectGroup(int index)
    {
        if (_pending)
            return;

        _group = index;
        CrewList.DisposeAllChildren();
        _crewButtons.Clear();
        PickCrew.Pressed = false;
        if (SelectedGroup is { } group)
        {
            if (group.Department != null)
                TargetSelect.SelectId(index);
            Amount.IsValid = value => value >= 1 && value <= group.MaxAmount;
            Amount.OverrideValue(group.DefaultAmount);
            AmountLabel.Text = Loc.GetString(group.Department == null ? "pirate-rev-ui-crew-percent" : "pirate-rev-ui-cut-percent");
            AmountRange.Text = Loc.GetString("pirate-rev-ui-amount-range", ("max", group.MaxAmount));
            foreach (var target in group.Crew)
            {
                var check = new CheckBox { Text = target.Name, ClipText = true, ToolTip = target.Name };
                check.Label.HorizontalExpand = true;
                check.OnToggled += _ => UpdateCrewSelection();
                _crewButtons.Add(check);
                CrewList.AddChild(check);
            }
        }

        UpdateConfiguration();
    }

    private void UpdateConfiguration()
    {
        RefreshButton.Disabled = _pending;
        RandomButton.Disabled = _pending || _option < 0;
        TargetSelect.Disabled = _pending;
        for (var i = 0; i < _orderButtons.Count; i++)
        {
            var (button, caption) = _orderButtons[i];
            button.Disabled = _pending || _options[i].Unavailable != null;
            caption.ModulateSelfOverride = button.Disabled ? Color.White.WithAlpha(0.5f) : null;
        }

        Targets.Visible = SelectedGroup != null;
        DepartmentRow.Visible = SelectedGroup?.Department != null;
        var target = SelectedOrder?.FixedTarget;
        FixedTarget.Visible = target != null;
        if (target != null)
            SetText(FixedTarget, Loc.GetString("pirate-rev-ui-fixed-target", ("target", target)));

        Amount.LineEditDisabled = _pending;
        Amount.SetButtonDisabled(_pending);
        FineRow.Visible = SelectedOrder?.HasFine == true;
        Fine.LineEditDisabled = _pending;
        Fine.SetButtonDisabled(_pending);
        if (!_pending)
            Fine.OverrideValue(Fine.Value);
        if (!_pending && SelectedGroup != null)
            Amount.OverrideValue(Amount.Value);
        UpdateCrewSelection();
    }

    private void UpdateCrewSelection()
    {
        var group = SelectedGroup;
        var hasCrew = group is { Crew.Count: > 0 };
        var manual = hasCrew && PickCrew.Pressed;
        var count = _crewButtons.Count(button => button.Pressed);
        PickCrew.Visible = hasCrew;
        PickCrew.Disabled = _pending;
        CrewScroll.Visible = manual;
        CrewCount.Visible = manual;
        AmountRow.Visible = group != null && !manual;
        CrewCount.Text = Loc.GetString("pirate-rev-ui-crew-count", ("count", count));
        foreach (var button in _crewButtons)
            button.Disabled = _pending;
        ReviewButton.Disabled = _pending || _option < 0 || (manual && count == 0);
    }

    private void Randomize()
    {
        var available = Enumerable.Range(0, _options.Count).Where(i => _options[i].Unavailable == null).ToList();
        if (_pending || available.Count == 0)
            return;

        OrderSearch.SetText(string.Empty, invokeEvent: true);
        var random = Random.Shared;
        SelectOrder(available[random.Next(available.Count)]);
        if (SelectedOrder is { Groups.Count: > 0 } order)
        {
            SelectGroup(random.Next(order.Groups.Count));
            if (SelectedGroup is { } group)
                Amount.OverrideValue(random.Next(1, group.MaxAmount + 1));

            if (order.HasFine)
                Fine.OverrideValue(random.Next(RevOrderTaxFine.RandomMin / RevOrderTaxFine.Step,
                    RevOrderTaxFine.RandomMax / RevOrderTaxFine.Step + 1) * RevOrderTaxFine.Step);
        }

        RequestReview();
    }

    private void RequestReview()
    {
        if (ReviewButton.Disabled)
            return;

        var manual = SelectedGroup is { Crew.Count: > 0 } && PickCrew.Pressed;
        var crew = manual ? Enumerable.Range(0, _crewButtons.Count).Where(i => _crewButtons[i].Pressed).ToArray() : [];
        var amount = SelectedGroup == null || manual ? 0 : Amount.Value;
        var fine = SelectedOrder?.HasFine == true ? Fine.Value : 0;
        Request(new RevOrderPrepare(_revision, _option, _group, amount, crew, fine));
    }

    private void SetPreview(RevOrderPreview preview)
    {
        ReviewName.Text = SelectedOrder?.Name;
        ReviewName.ToolTip = ReviewName.Text;
        var summary = preview.Effect ?? string.Empty;
        if (preview.Target is { } target)
        {
            var targetLine = Loc.GetString("pirate-rev-ui-review-target", ("target", target));
            summary = preview.Effect == null ? targetLine : $"{targetLine}\n{summary}";
        }
        SetText(ReviewTarget, summary);
        Tokens.DisposeAllChildren();
        Tokens.Visible = preview.Values.Count > 0;
        foreach (var token in preview.Values.Keys)
        {
            var text = RevOrderAnnouncement.Token(token);
            var button = new Button { Text = text, ToolTip = Loc.GetString("pirate-rev-ui-insert", ("token", text)) };
            button.OnPressed += _ =>
            {
                if (_pending)
                    return;

                Template.GrabKeyboardFocus();
                Template.InsertAtCursor(text);
            };
            Tokens.AddChild(button);
        }

        Template.TextRope = new Rope.Leaf(preview.Template);
        Template.CursorPosition = new TextEdit.CursorPos(preview.Template.Length, TextEdit.LineBreakBias.Top);
    }

    private void UpdatePreview()
    {
        if (_preview is not { } preview)
            return;

        if (_applyButton.IsConfirming)
            ResetConfirmation();

        var message = RevOrderAnnouncement.Render(Rope.Collapse(Template.TextRope), preview.Values, out var error);
        SetText(TemplateError, error ?? string.Empty, Color.Orange);
        _applyButton.Visible = !_pending && message != null;
        if (message == null)
        {
            SetText(Announcement, string.Empty);
            return;
        }

        var markup = Loc.GetString("chat-manager-sender-announcement-wrap-message",
            ("sender", FormattedMessage.EscapeText(preview.Sender)), ("message", FormattedMessage.EscapeText(message)));
        Announcement.SetMessage(FormattedMessage.FromMarkupOrThrow(markup), AnnouncementTags, Color.Gold);
    }

    private void ResetConfirmation()
    {
        Confirmation.DisposeAllChildren();
        _applyButton = new ConfirmButton
        {
            Text = Loc.GetString("pirate-rev-ui-apply"),
            ConfirmationText = Loc.GetString("pirate-rev-ui-confirm"),
            ResetTime = TimeSpan.FromSeconds(5),
            MinWidth = 170,
        };
        _applyButton.OnPressed += _ => Request(new RevOrderApply(_revision, Rope.Collapse(Template.TextRope)));
        Confirmation.AddChild(_applyButton);
    }

    private void Request(EuiMessageBase message)
    {
        if (_pending)
            return;

        _pending = true;
        SetStatus(Loc.GetString("pirate-rev-ui-wait"));
        UpdateConfiguration();
        Template.Editable = false;
        BackButton.Disabled = true;
        _applyButton.Visible = false;
        OnRequest?.Invoke(message);
    }

    private void SetStatus(string? text)
    {
        Status.Visible = text != null;
        SetText(Status, text ?? string.Empty);
    }

    private static void SetText(RichTextLabel label, string text, Color? color = null)
    {
        var message = new FormattedMessage();
        message.AddText(text);
        label.SetMessage(message, color);
    }
}
