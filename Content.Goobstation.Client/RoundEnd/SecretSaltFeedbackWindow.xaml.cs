using System;
using System.Collections.Generic;
using Content.Client.UserInterface.Controls;
using Content.Goobstation.Common.SecretSalt;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Goobstation.Client.RoundEnd;

[GenerateTypedNameReferences]
public sealed partial class SecretSaltFeedbackWindow : FancyWindow
{
    private int _rating;
    public event Action<int, SecretSaltFeedbackReason[], string?>? Submitted;

    public SecretSaltFeedbackWindow()
    {
        RobustXamlLoader.Load(this);

        for (var value = 1; value <= 5; value++)
        {
            var score = value;
            var button = new Button { Text = value.ToString(), MinWidth = 66 };
            button.OnPressed += _ =>
            {
                _rating = score;
                StatusLabel.Text = $"Оцінка: {score} із 5";
                SendButton.Disabled = false;
            };
            RatingButtons.AddChild(button);
        }

        SkipButton.OnPressed += _ => Close();
        SendButton.OnPressed += _ =>
        {
            if (_rating is < 1 or > 5)
                return;

            var comment = Rope.Collapse(CommentInput.TextRope);
            if (comment.Length > SecretSaltFeedbackValidator.MaxCommentLength)
            {
                StatusLabel.Text = "Коментар не повинен перевищувати 500 символів.";
                return;
            }

            var reasons = new List<SecretSaltFeedbackReason>();
            if (FewAntags.Pressed) reasons.Add(SecretSaltFeedbackReason.TooFewAntagonists);
            if (ManyAntags.Pressed) reasons.Add(SecretSaltFeedbackReason.TooManyAntagonists);
            if (FewEvents.Pressed) reasons.Add(SecretSaltFeedbackReason.TooFewEvents);
            if (TooChaotic.Pressed) reasons.Add(SecretSaltFeedbackReason.TooChaotic);
            if (Other.Pressed) reasons.Add(SecretSaltFeedbackReason.Other);
            Submitted?.Invoke(_rating, reasons.ToArray(), comment);
            Close();
        };
    }
}
