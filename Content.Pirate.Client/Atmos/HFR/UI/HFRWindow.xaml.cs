    public void SetStatus(float powerLevel, float integrity, float ironContent, float heatOutput, float heatLimiter, float energy,
        bool meltdownActive = false, float meltdownCountdown = 0f)
    {
        MeltdownWarningLabel.Visible = meltdownActive;
        MeltdownWarningLabel.Text = meltdownActive
            ? Loc.GetString("hfr-meltdown-ui-warning", ("seconds", Math.Max(0, (int) Math.Ceiling(meltdownCountdown))))
            : string.Empty;

        SetBar(PowerLevelBar, PowerLevelValue, powerLevel, 6f, $"{powerLevel:0}");
        SetBar(IntegrityBar, IntegrityValue, integrity, 100f, $"{integrity:F1}%");
        // Iron content can accumulate up to 300% (server clamp), so the bar must
        // span 300 too — otherwise it reads full while the value keeps climbing.
        SetBar(IronContentBar, IronContentValue, ironContent, 300f, $"{ironContent:F1}%");
        // E=mc² energy is astronomically large (c² ≈ 9e16). For display we strip the
        // light-speed amplifier AND the recipe's energy divisor, leaving the readable
        // "energy level" = energyModifiers * max(T*heatModifier/100, 1) in J/kJ/MJ —
        // nonzero whenever the fusion mix is healthy and growing with temperature.
        var recipe = HfrRecipes.All[Math.Clamp(_currentRecipe, 0, HfrRecipes.All.Length - 1)];
        var displayEnergy = energy / (HFRConstants.LightSpeed * HFRConstants.LightSpeed) * recipe.EnergyModifier;
        SetBar(EnergyBar, EnergyValue, displayEnergy, AutoScale(displayEnergy),
            FormatNumber(displayEnergy, "J"));
        SetBar(HeatLimiterBar, HeatLimiterValue, heatLimiter, AutoScale(heatLimiter), FormatNumber(heatLimiter, "K"));
        // Heat output shown as a percentage of the limiter cap — the meaningful
        // comparison (per /tg/: reaching the cap means max reaction rate).
        var heatPct = heatLimiter > 0f ? heatOutput / heatLimiter * 100f : 0f;
        SetBar(HeatOutputBar, HeatOutputValue, MathF.Abs(heatPct), 100f,
            $"{heatPct:+#.##;-#.##;0}%");
    }

    /// <summary>
    ///     Switch states with the /tg/ interlock rules: the reactor cannot be powered
    ///     down while hot, cooling is locked while injection runs, and injection needs power+cooling.
    /// </summary>
    public void SetSwitches(bool power, bool cooling, bool fuel, bool moderator, float powerLevel)
    {
        var running = powerLevel > 0f;

        StartPowerToggle.Disabled = running;
        StartCoolingToggle.Disabled = fuel || moderator || !power || (cooling && running);
        FusionInjectionSwitch.Disabled = !power || !cooling;
        ModeratorInjectionSwitch.Disabled = !power || !cooling;

        _syncingUi = true;
        SetToggleState(StartPowerToggle, power);
        SetToggleState(StartCoolingToggle, cooling);
        SetToggleState(FusionInjectionSwitch, fuel);
        SetToggleState(ModeratorInjectionSwitch, moderator);
        _syncingUi = false;
    }

