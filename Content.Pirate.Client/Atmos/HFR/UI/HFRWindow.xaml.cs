    private void BuildRecipeCollapsible()
    {
        var body = new CollapsibleBody();
        var list = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 3,
            Margin = new Thickness(0, 6, 0, 0),
        };

        for (var i = 0; i < RecipeInfo.Length; i++)
        {
            var index = i;
            var (name, outputs) = RecipeInfo[i];

            var button = new Button { Text = name, StyleClasses = { "OpenBoth" }, HorizontalExpand = true };
            button.OnPressed += _ =>
            {
                if (_powerLevel > 0f)
                    return; // recipes can only be changed while the reactor is cold (per /tg/)
                OnRecipeSelected?.Invoke(index);
            };
            list.AddChild(button);
            list.AddChild(new Label
            {
                Text = outputs,
                FontColorOverride = Color.FromHex("#808080"),
            });
            _recipeButtons.Add(button);
        }

        body.AddChild(list);
        RecipeHost.AddChild(new Collapsible("Recipe selection", body));
    }

