    /// <summary>
    ///     Toggles the full gas readout panel and refreshes its contents from the
    ///     last received fusion/moderator gas dictionaries.
    /// </summary>
    private void ToggleGasReadout()
    {
        var show = !GasReadoutPanel.Visible;
        GasReadoutPanel.Visible = show;
        ShowGasesButton.Text = show ? "Hide mix gases" : "Show mix gases";
        if (show)
            RefreshGasReadout();
    }

    private void RefreshGasReadout()
    {
        FusionReadoutLabel.SetMessage(BuildGasReadout(_fusionGases, "No fuel gases present"));
        ModeratorReadoutLabel.SetMessage(BuildGasReadout(_moderatorGases, "No moderator gases present"));
    }

    /// <summary>
    ///     Builds a multi-line readout of every gas in the mix, sorted by moles
    ///     descending, using the same labels/colors as the per-gas bars.
    /// </summary>
    private static FormattedMessage BuildGasReadout(IReadOnlyDictionary<Gas, float> gases, string emptyText)
    {
        var msg = new FormattedMessage();
        var items = gases.OrderByDescending(kv => kv.Value).ToList();
        if (items.Count == 0)
        {
            msg.AddText(emptyText);
            return msg;
        }

        for (var i = 0; i < items.Count; i++)
        {
            var (gas, moles) = items[i];
            var label = GasInfo.TryGetValue(gas, out var info) ? info.Label : gas.ToString();
            var color = GasInfo.TryGetValue(gas, out var info2) ? info2.Color : Color.White;
            msg.PushColor(color);
            msg.AddText($"{label}: ");
            msg.Pop();
            msg.AddText($"{moles:F2} mol");
            if (i < items.Count - 1)
                msg.AddText("\n");
        }

        return msg;
    }

