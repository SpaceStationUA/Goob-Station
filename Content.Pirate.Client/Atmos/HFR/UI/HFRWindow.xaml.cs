    {
        _font = new VectorFont(
            IoCManager.Resolve<IResourceCache>().GetResource<FontResource>("/Fonts/NotoSans/NotoSans-Regular.ttf"),
            11);
        HorizontalExpand = true;
        VerticalExpand = true;
        MinSize = new Vector2(AxisWidth + ChartWidth + 8f, ChartHeight + 64f);
    }

    public void UpdateData(float[] values, float[] deltas, float powerLevel, float maxLevelTemp)
    {
        Array.Copy(values, _values, Math.Min(values.Length, _values.Length));
        Array.Copy(deltas, _deltas, Math.Min(deltas.Length, _deltas.Length));
        _powerLevel = powerLevel;
        _maxLevelTemp = maxLevelTemp;
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        var scale = UIScale;

        // Fill the full control size, not a fixed rectangle.
        var chartWidth = MathF.Max(ChartWidth, Size.X - AxisWidth - 8f);
        var chartHeight = MathF.Max(ChartHeight, Size.Y - 64f);
        var totalWidth = AxisWidth + chartWidth + 8f;

        // Background.
        handle.DrawRect(UIBox2.FromDimensions(Vector2.Zero, new Vector2(totalWidth, chartHeight) * scale), Bg);

        // Log-scale bounds (single pass, no allocation).
        var minPositive = float.MaxValue;
        var maxTemp = 1000f;
        foreach (var v in _values)
        {
            if (v <= 0f)
                continue;
            if (v < minPositive)
                minPositive = v;
            if (v > maxTemp)
                maxTemp = v;
        }

        // Everything above 20 K starts the axis at 20 (so a hot reactor doesn't
        // compress the scale with a 2.7 K floor); otherwise clamp to [2.73, 20].
        var minTemp = minPositive == float.MaxValue
            ? 2.73f
            : Math.Clamp(minPositive, 2.73f, 20f);

        var prevLevel = 0f;
        var nextLevel = 0f;
        switch ((int) _powerLevel)
        {
            case 0: nextLevel = 500f; break;
            case 1: prevLevel = 500f; nextLevel = 1000f; break;
            case 2: prevLevel = 1000f; nextLevel = 10000f; break;
            case 3: prevLevel = 10000f; nextLevel = 100000f; break;
            case 4: prevLevel = 100000f; nextLevel = 1000000f; break;
            case 5: prevLevel = 1000000f; nextLevel = 10000000f; break;
            default: prevLevel = 10000000f; nextLevel = _maxLevelTemp; break;
        }

        maxTemp = Math.Max(maxTemp, Math.Max(prevLevel, nextLevel));
        if (maxTemp <= minTemp)
            maxTemp = minTemp * 2f;

        float Ratio(float v)
        {
            if (v <= 0f)
                return 0f;
            var r = (MathF.Log10(v) - MathF.Log10(minTemp))
                / (MathF.Log10(maxTemp) - MathF.Log10(minTemp));
            return Math.Clamp(r, 0f, 1f);
        }

        // Y-axis ticks at the power level boundaries.
        DrawTick(handle, scale, minTemp, Ratio, chartWidth, chartHeight, LabelColor);
        if (prevLevel > 0f)
            DrawTick(handle, scale, prevLevel, Ratio, chartWidth, chartHeight, LabelColor);
        DrawTick(handle, scale, nextLevel, Ratio, chartWidth, chartHeight, LabelColor);
        DrawTick(handle, scale, maxTemp, Ratio, chartWidth, chartHeight, LabelColor);

        // Bars + legend, spaced evenly across the full chart width.
        var barSpacing = (chartWidth - 44f) / 4f;
        for (var i = 0; i < Series.Length; i++)
        {
            var barX = AxisWidth + 22f + i * barSpacing;
            var centerX = barX + 7f;
            var value = _values[i];

            if (value > 0f)
            {
                var height = chartHeight * Ratio(value);
                handle.DrawRect(
                    UIBox2.FromDimensions(
                        new Vector2(barX, chartHeight - height) * scale,
                        new Vector2(14f, height) * scale),
                    Series[i].Color);
            }

            // Legend: name / value / delta under each bar.
            DrawCentered(handle, scale, centerX, chartHeight + 4f, Series[i].Name, LabelColor);
            if (value > 0f)
            {
                DrawCentered(handle, scale, centerX, chartHeight + 19f, FormatTemp(value), Color.White);
                var delta = _deltas[i];
                var deltaText = delta == 0f
                    ? "-"
                    : $"{(delta > 0f ? "+" : "")}{FormatTemp(delta)} K/s";
                DrawCentered(handle, scale, centerX, chartHeight + 34f, deltaText, LabelColor);
            }
            else
            {
                DrawCentered(handle, scale, centerX, chartHeight + 19f, "Empty", EmptyColor);
            }
        }
    }

    private void DrawTick(DrawingHandleScreen handle, float scale, float value, Func<float, float> ratio, float chartWidth, float chartHeight, Color color)
    {
        var y = (chartHeight - ratio(value) * chartHeight) * scale;
        handle.DrawRect(
            UIBox2.FromDimensions(new Vector2(AxisWidth * scale, y), new Vector2(chartWidth * scale, 1f)),
            TickColor);

        var text = FormatTemp(value);
        var dims = handle.GetDimensions(_font, text, scale);
        handle.DrawString(_font, new Vector2((AxisWidth - 4f) * scale - dims.X, y - dims.Y / 2f), text, scale, color);
    }

    private void DrawCentered(DrawingHandleScreen handle, float scale, float centerX, float topY, string text, Color color)
    {
        var dims = handle.GetDimensions(_font, text, scale);
        handle.DrawString(
            _font,
            new Vector2(centerX * scale - dims.X / 2f, topY * scale),
            text,
            scale,
            color);
    }

    private static string FormatTemp(float value)
    {
        var abs = MathF.Abs(value);
        if (abs >= 1e6f)
            return $"{value / 1e6f:0.##}M";
        if (abs >= 1e3f)
            return $"{value / 1e3f:0.##}k";
        return MathF.Round(value).ToString(CultureInfo.InvariantCulture);
    }
