    private void SetToggleState(Button button, bool on)
    {
        button.Pressed = on;
        button.Text = on ? "On" : "Off";
    }

    /// <summary>
    ///     Shared handler for the toggle buttons. Updates the On/Off label immediately
    ///     (optimistic UI) and only relays the change to the server when it came from a
    ///     user click. Programmatic state syncs (server echoes) must not re-send:
    ///     setting <see cref="Button.Pressed"/> fires OnToggled again, so an echo that
    ///     arrives after the click would otherwise overwrite the player's choice.
    /// </summary>
    private void OnToggleChanged(Button button, bool pressed, Action<bool>? send)
    {
        if (_syncingUi)
            return;

        button.Text = pressed ? "On" : "Off";
        send?.Invoke(pressed);
    }

    // Mole-bar scale caps: fusion bars fill at 1000 moles, moderator bars at 500
    // (per /tg/ moderator scale). Values above the cap are clamped so both the bar
    // and the readout stop at a readable maximum instead of "flying into space".
    private const float FusionBarMaxMoles = 1000f;
    private const float ModeratorBarMaxMoles = 500f;

    private void RebuildGasLists()
    {
        // Fusion: sticky gases = the selected recipe's fuel requirements.
        var recipe = HfrRecipes.All[Math.Clamp(_currentRecipe, 0, HfrRecipes.All.Length - 1)];
        RebuildGasList(FusionGasList, _fusionGases, [recipe.PrimaryFuel, recipe.SecondaryFuel], FusionBarMaxMoles);
        RebuildGasList(ModeratorGasList, _moderatorGases, StickyModeratorGases, ModeratorBarMaxMoles);
    }

    private static void RebuildGasList(BoxContainer list, IReadOnlyDictionary<Gas, float> gases, IReadOnlyList<Gas> sticky, float maxScale)
    {
        list.RemoveAllChildren();

        var items = gases.OrderByDescending(kv => kv.Value).ToList();
        foreach (var gas in sticky)
        {
            if (!items.Any(i => i.Key == gas))
                items.Add(new KeyValuePair<Gas, float>(gas, 0f));
        }

        foreach (var (gas, moles) in items)
        {
            if (!GasInfo.TryGetValue(gas, out var info))
                continue;

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 5,
            };
            row.AddChild(new Label
            {
                Text = info.Label + ":",
                SetWidth = 92,
                VerticalAlignment = Control.VAlignment.Center,
            });

            // Bar fills relative to the scale cap; the displayed number is clamped
            // to the same cap so it never outgrows the bar's meaning.
            var displayMoles = Math.Min(moles, maxScale);
            var bar = new ProgressBar
            {
                HorizontalExpand = true,
                SetHeight = 14,
                VerticalAlignment = Control.VAlignment.Center,
                MaxValue = maxScale,
                Value = displayMoles,
                ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = info.Color },
                BackgroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = new Color(0.12f, 0.12f, 0.14f, 1f) },
            };
            row.AddChild(bar);

            // Wide enough that "1000.00 moles" never spills back over the bar.
            row.AddChild(new Label
            {
                Text = $"{displayMoles:F2} moles",
                Align = Label.AlignMode.Right,
                SetWidth = 105,
                VerticalAlignment = Control.VAlignment.Center,
            });

            list.AddChild(row);
        }
    }

    private static void SetBar(ProgressBar bar, Label label, float value, float max, string text)
    {
        label.Text = text;
        bar.MaxValue = Math.Max(max, 1f);
        bar.Value = Math.Clamp(value, 0f, bar.MaxValue);
    }

    private static void SetInput(LineEdit input, float value)
    {
        if (!input.HasKeyboardFocus())
            input.Text = value.ToString("0.##", CultureInfo.InvariantCulture);
    }

    private static float AutoScale(float value)
    {
        return Math.Max(value * 1.2f, 1f);
    }

    private static readonly (float Divisor, string Suffix)[] NumberPrefixes =
    [
        (1e30f, "Q"), (1e27f, "R"), (1e24f, "Y"), (1e21f, "Z"), (1e18f, "E"),
        (1e15f, "P"), (1e12f, "T"), (1e9f, "G"), (1e6f, "M"), (1e3f, "k"),
    ];

    /// <summary>
    ///     Formats a status value with SI prefixes (k/M/G/T/P/E/Z/Y/R/Q) so the huge
    ///     E=mc² energy and heat figures stay readable, e.g. "10 EJ" or "5 MK".
    /// </summary>
    private static string FormatNumber(float value, string unit)
    {
        var abs = MathF.Abs(value);
        if (abs < 1e3f)
            return $"{value:0.##}{unit}";

        // Pick the largest prefix that keeps the displayed value below 1000
        // (so even the energy clamp 1e35 renders as "100 QJ", not "100000QJ").
        foreach (var (divisor, suffix) in NumberPrefixes)
        {
            if (abs >= divisor)
                return $"{value / divisor:0.##}{suffix}{unit}";
        }

        return $"{value:0.##}{unit}";
    }

    private static float ParseFloat(string text)
    {
        return float.TryParse(text, NumberStyles.Float, CultureInfo.InvariantCulture, out var result) ? result : 0f;
    }
