using System.Linq;
using Content.Client._Pirate.StationRecords;
using Content.Pirate.Shared._Pirate.StationRecords;
using Content.Shared._Pirate.StationRecords;
using Content.Shared.StationRecords;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Pirate.Client._Pirate.StationRecords;

[GenerateTypedNameReferences]
public sealed partial class RecordsCartridgeUiFragment : BoxContainer
{
    public event Action<RecordsCartridgeTab, BoundUserInterfaceMessage?>? OnMessage;

    private readonly Dictionary<RecordsCartridgeTab, Page> _pages = new();
    private RecordsCartridgeTab _tab;
    private bool _gotState;

    public RecordsCartridgeUiFragment()
    {
        RobustXamlLoader.Load(this);

        foreach (var tab in Enum.GetValues<RecordsCartridgeTab>())
        {
            var page = new Page(tab, message => OnMessage?.Invoke(tab, message));
            ListColumn.AddChild(page.ListBox);
            HistoryColumn.AddChild(page.HistoryBox);
            _pages[tab] = page;
        }

        SecurityTabButton.OnPressed += _ => SwitchTab(RecordsCartridgeTab.Security);
        CrewTabButton.OnPressed += _ => SwitchTab(RecordsCartridgeTab.Crew);
        PsionicsTabButton.OnPressed += _ => SwitchTab(RecordsCartridgeTab.Psionics);

        ShowTab(_tab);
    }

    public void UpdateState(RecordsCartridgeUiState state)
    {
        // Preserve the user-selected tab on later updates.
        if (!_gotState)
        {
            _gotState = true;
            ShowTab(state.Tab);
        }

        foreach (var page in state.Pages)
        {
            if (_pages.TryGetValue(page.Tab, out var view))
                view.Update(page);
        }
    }

    private void SwitchTab(RecordsCartridgeTab tab)
    {
        if (tab != _tab)
        {
            // Remember the tab for the next opening.
            OnMessage?.Invoke(tab, null);
        }

        ShowTab(tab);
    }

    private void ShowTab(RecordsCartridgeTab tab)
    {
        _tab = tab;
        foreach (var (pageTab, page) in _pages)
        {
            page.SetVisible(pageTab == tab);
        }

        SecurityTabButton.Pressed = tab == RecordsCartridgeTab.Security;
        CrewTabButton.Pressed = tab == RecordsCartridgeTab.Crew;
        PsionicsTabButton.Pressed = tab == RecordsCartridgeTab.Psionics;
    }

    private sealed class Page
    {
        public readonly BoxContainer ListBox;
        public readonly BoxContainer HistoryBox;

        private readonly Action<BoundUserInterfaceMessage> _send;
        private readonly Label _noRecords;
        private readonly Label _unselected;
        private readonly RecordHistoryPanel _history;
        private readonly RecordSelectionController<RecordsCartridgePage> _selection;
        private RecordsCartridgePage? _shown;

        public Page(RecordsCartridgeTab tab, Action<BoundUserInterfaceMessage> send)
        {
            _send = send;

            _noRecords = new Label
            {
                HorizontalExpand = true,
                Align = Label.AlignMode.Center,
                FontColorOverride = Color.DarkGray,
                Visible = false,
            };
            var list = new ItemList();
            var scroll = new ScrollContainer { VerticalExpand = true, HScrollEnabled = false };
            scroll.AddChild(list);
            ListBox = new BoxContainer { Orientation = LayoutOrientation.Vertical, VerticalExpand = true };
            ListBox.AddChild(_noRecords);
            ListBox.AddChild(scroll);

            _unselected = new Label
            {
                Text = Loc.GetString("records-cartridge-select-record"),
                HorizontalExpand = true,
                Align = Label.AlignMode.Center,
                FontColorOverride = Color.DarkGray,
                Visible = false,
            };
            _history = new RecordHistoryPanel
            {
                PdaLayout = true,
                Visible = false,
                Book = tab switch
                {
                    RecordsCartridgeTab.Security => RecordLogBook.Security,
                    RecordsCartridgeTab.Psionics => RecordLogBook.Psionics,
                    _ => RecordLogBook.Crew,
                },
            };
            _history.OnAddNote += text => _send(new RecordLogAddNoteMessage(text));
            _history.OnDeleteEntry += id => _send(new RecordLogDeleteMessage(id));
            HistoryBox = new BoxContainer
            {
                Orientation = LayoutOrientation.Vertical,
                HorizontalExpand = true,
                VerticalExpand = true,
            };
            HistoryBox.AddChild(_unselected);
            HistoryBox.AddChild(_history);

            _selection = new RecordSelectionController<RecordsCartridgePage>(list);
            _selection.SelectionRequested += key => _send(new SelectStationRecord(key) { Request = _selection.LastRequest });
            _selection.ShowCached += (cached, last) => Update(last.WithRecordOf(cached));
        }

        public void SetVisible(bool visible)
        {
            ListBox.Visible = visible;
            HistoryBox.Visible = visible;
            if (!visible)
                _history.CloseDialog();
        }

        public void Update(RecordsCartridgePage state)
        {
            ShowListing(state.RecordListing);

            if (!_selection.AcceptServerState(state, state.SelectedKey, state.SelectionRequest, state.HasRecord))
                return;

            if (!state.HasRecord || state is not { SelectedKey: { } key, Name: { } name })
            {
                _shown = null;
                _history.CloseDialog();
                _history.Visible = false;
                _unselected.Visible = state.RecordListing is { Count: > 0 };
                return;
            }

            _unselected.Visible = false;
            _history.Visible = true;

            // Avoid rebuilding history when other records change.
            if (_shown is { } shown
                && shown.SelectedKey == key
                && shown.Name == name
                && shown.CanEdit == state.CanEdit
                && shown.Log!.SequenceEqual(state.Log!))
            {
                return;
            }

            _shown = state;
            _history.UpdateLog(key, name, state.Log, state.CanEdit);
        }

        private void ShowListing(Dictionary<uint, string>? listing)
        {
            _noRecords.Visible = listing is not { Count: > 0 };
            _noRecords.Text = Loc.GetString(listing == null ? "records-cartridge-no-station" : "records-cartridge-no-records");
            _selection.SetListing(listing);
        }
    }
}
