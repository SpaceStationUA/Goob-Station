using System.Linq;
using Content.Pirate.Shared.Caduceus;
using Content.Pirate.Shared.Index;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Utility;

namespace Content.Pirate.Client.Index;

[GenerateTypedNameReferences]
public sealed partial class IndexAdminMenuWindow : DefaultWindow
{
    public Action<string>? OnSendPrescription;
    public Action<int>? OnAddKarma;
    public Action<int>? OnRemoveKarma;
    public Action<CaduceusForm?>? OnNextWeaponSelected;
    public Action? OnJumpscare;

    private static readonly Color PrescriptionColor = Color.FromHex("#F2D3A0");

    // Dropdown choices: null = no override (normal queued form), then every weapon form (fpoon included).
    private readonly List<CaduceusForm?> _nextWeaponChoices = new()
    {
        null,
        CaduceusForm.Hatchet,
        CaduceusForm.Stiletto,
        CaduceusForm.BastardSword,
        CaduceusForm.Rapier,
        CaduceusForm.Hammer,
        CaduceusForm.Greatsword,
        CaduceusForm.Lance,
        CaduceusForm.Whip,
        CaduceusForm.Scythe,
        CaduceusForm.Fpoon,
    };

    [Dependency] private readonly IResourceCache _resourceCache = default!;

    private static readonly ResPath IndexLogoPath = new("/Textures/_Pirate/Interface/Misc/index.rsi");

    public IndexAdminMenuWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        IndexLogo.Texture = _resourceCache.GetResource<RSIResource>(IndexLogoPath).RSI["index"].Frame0;

        SendButton.OnPressed += _ => SendPrescription();
        PrescriptionInput.OnTextEntered += _ => SendPrescription();

        AddOneButton.OnPressed += _ => OnAddKarma?.Invoke(1);
        AddFiveButton.OnPressed += _ => OnAddKarma?.Invoke(5);
        RemoveOneButton.OnPressed += _ => OnRemoveKarma?.Invoke(1);
        RemoveFiveButton.OnPressed += _ => OnRemoveKarma?.Invoke(5);

        NextWeaponOptions.AddItem(Loc.GetString("index-admin-next-weapon-random"));
        foreach (var form in _nextWeaponChoices.Skip(1))
        {
            if (form is not { } weaponForm)
                continue;

            NextWeaponOptions.AddItem(Loc.GetString($"caduceus-form-{FormKey(weaponForm)}"));
        }

        NextWeaponOptions.OnItemSelected += args =>
        {
            NextWeaponOptions.SelectId(args.Id);
            OnNextWeaponSelected?.Invoke(_nextWeaponChoices[args.Id]);
        };

        JumpscareButton.OnPressed += _ => OnJumpscare?.Invoke();
    }

    private static string FormKey(CaduceusForm form)
    {
        return form.ToString().ToLowerInvariant();
    }

    private void SendPrescription()
    {
        var text = PrescriptionInput.Text.Trim();
        if (string.IsNullOrEmpty(text))
            return;

        OnSendPrescription?.Invoke(text);
        PrescriptionInput.Text = string.Empty;
    }

    public void UpdateState(IndexAdminBoundUserInterfaceState state)
    {
        KarmaLabel.Text = Loc.GetString("index-karma-label", ("karma", state.KarmicConsequence));
        MemberNameLabel.Text = state.HasMember
            ? Loc.GetString("index-admin-member-label", ("name", state.MemberName))
            : Loc.GetString("index-admin-no-member");

        var lastPrescription = string.IsNullOrEmpty(state.LastPrescription)
            ? Loc.GetString("index-admin-no-prescriptions")
            : state.LastPrescription;
        LastPrescriptionLabel.SetMessage(FormattedMessage.FromUnformatted(lastPrescription), PrescriptionColor);

        var selected = _nextWeaponChoices.IndexOf(state.NextWeapon);
        if (selected < 0)
            selected = 0;

        if (NextWeaponOptions.SelectedId != selected)
            NextWeaponOptions.SelectId(selected);
    }
}
