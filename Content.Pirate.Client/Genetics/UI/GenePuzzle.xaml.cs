namespace Content.Pirate.Client.Genetics.UI;

[GenerateTypedNameReferences]
public sealed partial class GenePuzzle : Control
{
    public event Action<uint, GeneticsCycle>? OnSetBase;
    public event Action? OnSequence;
    public event Action? OnResetSequence;

    public event Action<uint>? OnJoker;

    private bool _busy;
    private bool _sequenced;
    private bool _jokerMode;
    private int _jokerCooldown;
    private bool _writable = true;
    private string _bases = string.Empty;
    private string _originalBases = string.Empty;
    private readonly List<Button> _buttons = new();

    public static readonly Color Green = new(110, 255, 110);
    public static readonly Color Blue = new(130, 200, 255);
    public static readonly Color GroupBorder = Color.FromHex("#50AAFF");

    private const int PairsPerGroup = 4;

    public GenePuzzle()
    {
        RobustXamlLoader.Load(this);

        SequenceButton.OnPressed += _ => OnSequence?.Invoke();
        ResetSequenceButton.OnPressed += _ => OnResetSequence?.Invoke();
        JokerButton.OnPressed += _ => SetJokerMode(JokerButton.Pressed);
        CreateBaseButtons(MutationData.BaseCount);
        ClearBases();
    }

    public void MakeReadonly()
    {
        _writable = false;
        Tip.Visible = false;
        SequenceButtonContainer.Visible = false;
        UpdateBaseButtons();
    }

    public void SetJokerCooldown(int? cooldown)
    {
        JokerButton.Visible = cooldown != null;
        var seconds = cooldown ?? 0;
        if (seconds == _jokerCooldown)
            return;

        _jokerCooldown = seconds;
        JokerButton.Text = seconds > 0
            ? Loc.GetString("genetics-console-joker-cooldown", ("seconds", seconds))
            : Loc.GetString("genetics-console-joker");
        UpdateJokerButton();
    }

    private void SetJokerMode(bool on)
    {
        _jokerMode = on && !JokerButton.Disabled;
        JokerButton.Pressed = _jokerMode;
    }

    private void UpdateJokerButton()
    {
        JokerButton.Disabled = _busy || !_writable || _sequenced || _jokerCooldown > 0 || !_originalBases.Contains('X');
        if (JokerButton.Disabled)
            SetJokerMode(false);
    }

    private void UpdateSequenceButton()
    {
        UpdateJokerButton();
        SequenceButton.Disabled = _busy || _sequenced || !IsComplete();
        ResetSequenceButton.Disabled = _busy || _bases == _originalBases;
    }

    private bool IsComplete()
    {
        if (_bases.Length == 0)
            return false;

        foreach (var c in _bases)
        {
            if (c == 'X') return false;
        }

        return true;
    }

    public void SetBusy(bool busy)
    {
        _busy = busy;
        UpdateBaseButtons();
        UpdateSequenceButton();
    }

    public void SetSequenced(bool sequenced)
    {
        _sequenced = sequenced;
        UpdateSequenceButton();
    }

    public void ClearBases()
    {
        _bases = string.Empty;
        _originalBases = string.Empty;
        NoSequence.Visible = true;
        BaseButtons.Modulate = Color.Transparent;
        foreach (var button in _buttons)
        {
            button.Disabled = true;
        }
        UpdateSequenceButton();
    }

    public void SetBases(string bases, string originalBases)
    {
        _bases = bases;
        _originalBases = originalBases;
        NoSequence.Visible = false;
        BaseButtons.Modulate = Color.White;
        if (_buttons.Count != bases.Length)
            CreateBaseButtons(bases.Length);
        UpdateBaseButtons();
        UpdateSequenceButton();
    }

    private void CreateBaseButtons(int count)
    {
        _buttons.Clear();
        BaseButtons.RemoveAllChildren();
        for (var i = 0; i < count; i++)
            _buttons.Add(CreateBase((uint) i));

        var pairs = count / 2;
        BoxContainer? group = null;
        for (var p = 0; p < pairs; p++)
        {
            if (p % PairsPerGroup == 0)
            {
                group = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    Margin = new Thickness(4)
                };
                BaseButtons.AddChild(new PanelContainer
                {
                    PanelOverride = new StyleBoxFlat { BorderColor = GroupBorder, BorderThickness = new Thickness(1) },
                    Margin = new Thickness(2, 0),
                    Children = { group }
                });
            }

            var column = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                Margin = new Thickness(1, 0)
            };
            column.AddChild(_buttons[p]);
            column.AddChild(new Label
            {
                Text = "|",
                HorizontalAlignment = HAlignment.Center
            });
            column.AddChild(_buttons[p + pairs]);
            group!.AddChild(column);
        }
    }

    private void UpdateBaseButtons()
    {
        for (var i = 0; i < _buttons.Count && i < _bases.Length; i++)
        {
            var button = _buttons[i];
            var b = _bases[i];
            button.Text = b.ToString();
            button.Modulate = GetColor(b);
            button.Disabled = _busy || !_writable || _originalBases[i] != 'X';
        }
    }

    private Button CreateBase(uint i)
    {
        var button = new Button
        {
            MinSize = new Vector2(34, 30),
            TextAlign = Label.AlignMode.Center,
            StyleClasses = { "ButtonSquare" }
        };
        void Cycle(GeneticsCycle cycle)
        {
            if (_busy || !_writable || button.Disabled)
                return;
            var bases = _bases.ToCharArray();
            var b = GeneticsConsoleSystem.CycleBase(bases[i], cycle);
            bases[i] = b;
            _bases = new string(bases);
            button.Modulate = GetColor(b);

            button.Text = b.ToString();
            UpdateSequenceButton();
            OnSetBase?.Invoke(i, cycle);
        }

        button.OnKeyBindDown += args =>
        {
            if (args.Function == EngineKeyFunctions.UIRightClick)
                Cycle(GeneticsCycle.Last);
            else if (args.Function == ContentKeyFunctions.TryPullObject) // Ctrl click
                Cycle(GeneticsCycle.Reset);
        };
        button.OnPressed += _ =>
        {
            if (_jokerMode)
            {
                if (!_busy && _writable && !button.Disabled && _originalBases[(int) i] == 'X')
                    OnJoker?.Invoke(i);
                SetJokerMode(false);
                return;
            }

            Cycle(GeneticsCycle.Next);
        };
        return button;
    }

    private Color GetColor(char b)
        => b switch
        {
            'A' => Green,
            'T' => Green,
            'G' => Blue,
            'C' => Blue,
            _ => Color.White
        };
}
