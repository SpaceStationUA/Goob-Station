# The order states are listed in meta.json. Redo mirrors undo, previous mirrors next; the other arrows turn the up arrow.
ORDER = [
    "pencil", "eraser", "fill", "picker", "bodyeraser", "symmetry", "undo", "redo", "flip", "mirror", "trash",
    "left", "up", "down", "right", "export", "previous", "next", "add", "remove", "play",
]


def render(rows):
    image = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    assert len(rows) == 16, rows
    for y, row in enumerate(rows):
        assert len(row) == 16, row
        for x, char in enumerate(row):
            if char == "#":
                image.putpixel((x, y), (255, 255, 255, 255))
            elif char == "+":
                image.putpixel((x, y), (255, 255, 255, 140))
    return image


def icons():
    images = {name: render(rows) for name, rows in ICONS.items()}
    images["redo"] = images["undo"].transpose(Image.FLIP_LEFT_RIGHT)
    images["previous"] = images["next"].transpose(Image.FLIP_LEFT_RIGHT)
    images["down"] = images["up"].transpose(Image.FLIP_TOP_BOTTOM)
    images["left"] = images["up"].transpose(Image.ROTATE_90)
    images["right"] = images["up"].transpose(Image.ROTATE_270)
    assert set(ORDER) == set(images), set(images) ^ set(ORDER)
    return images


def write_preview(images, path, scale=6):
    cell = 16 * scale + 12
    sheet = Image.new("RGBA", (cell * len(ORDER), cell), (24, 35, 48, 255))
    for i, name in enumerate(ORDER):
        big = images[name].resize((16 * scale, 16 * scale), Image.NEAREST)
        sheet.alpha_composite(big, (i * cell + 6, 6))
    sheet.save(path)


def main():
    images = icons()
    if "--preview" in sys.argv:
        preview = Path(sys.argv[sys.argv.index("--preview") + 1])
        write_preview(images, preview)
        print("preview:", preview)

    RSI.mkdir(parents=True, exist_ok=True)
    for name in ORDER:
        images[name].save(RSI / f"{name}.png")
    meta = {
        "version": 1,
        "license": "CC-BY-SA-3.0",
        "copyright": "Made for Wolfgate (CustomMarkings) by Tools/_Pirate/CustomMarkings/gen_editor_icons.py",
        "size": {"x": 16, "y": 16},
        "states": [{"name": name} for name in ORDER],
    }
    with open(RSI / "meta.json", "w", newline="\n") as f:
        json.dump(meta, f, indent=2)
        f.write("\n")
    print("wrote", RSI)


if __name__ == "__main__":
    main()
